"""`rustsheet-gen` — generate synthetic spec cases into an eval suite.

  rustsheet-gen --milestone M2 --count 25 --seed 1 --suite gen-m2
  rustsheet-gen --policy operators-refs --seed 0          # suite gen-m1 (M1, no functions)
  rustsheet-gen --policy names-3d --seed 0                # suite gen-m8a (M8 names, 3-D refs)

Creates eval/suites/<suite>/suite.toml if missing (non-gating until oracle sidecars exist).
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from rustsheet_tools import repo_root
from rustsheet_tools.gen.generator import Catalog, generate_case, write_case
from rustsheet_tools.gen.names_3d import generate_names_3d
from rustsheet_tools.gen.numeric_rules import generate_numeric_rules
from rustsheet_tools.gen.operators_refs import generate_operators_refs

SUITE_TOML = """name = "{name}"
description = "{description}"
kind = "spec"
root = "cases"
include = ["**/*.case.json"]
license = "Apache-2.0"
origin = "generated"
gate = false
baseline = "cells"
milestone = ["{milestone}"]
"""


def write_suite(root: Path, name: str, description: str, milestone: str, specs: list[dict[str, Any]]) -> None:
    """Create eval/suites/<name>/suite.toml if missing and write each spec as a case file."""
    suite_dir = root / "eval" / "suites" / name
    if not (suite_dir / "suite.toml").exists():
        suite_dir.mkdir(parents=True, exist_ok=True)
        (suite_dir / "suite.toml").write_text(
            SUITE_TOML.format(name=name, description=description, milestone=milestone)
        )
    for spec in specs:
        print(write_case(spec, suite_dir / "cases").relative_to(root))


def main() -> None:
    ap = argparse.ArgumentParser(prog="rustsheet-gen", description=__doc__.splitlines()[0])
    ap.add_argument("--milestone", default="M2")
    ap.add_argument("--count", type=int, default=10)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--formulas", type=int, default=40)
    ap.add_argument("--depth", type=int, default=3)
    ap.add_argument("--suite", default=None, help="suite name (default gen-<milestone>)")
    ap.add_argument(
        "--policy",
        choices=["random", "numeric-rules", "operators-refs", "names-3d"],
        default="random",
        help=(
            "numeric-rules: dense floating-point probe batches (suite probes-numeric); "
            "operators-refs: M1 operators and references only, no functions (suite gen-m1, T-0117); "
            "names-3d: M8 defined names and 3-D references (suite gen-m8a, T-1606); "
            "all three ignore --milestone/--count/--formulas/--depth"
        ),
    )
    ap.add_argument("--catalog", type=Path, default=None)
    args = ap.parse_args()

    root = repo_root()
    if args.policy == "numeric-rules":
        write_suite(
            root,
            args.suite or "probes-numeric",
            "Floating-point rule probes from rustsheet-gen --policy numeric-rules; pending until the Excel oracle fills expectations",
            "M1",
            generate_numeric_rules(args.seed),
        )
        return
    if args.policy == "operators-refs":
        write_suite(
            root,
            args.suite or "gen-m1",
            "M1 operator and reference probes from rustsheet-gen --policy operators-refs; expectations from the Excel oracle",
            "M1",
            generate_operators_refs(args.seed),
        )
        return
    if args.policy == "names-3d":
        write_suite(
            root,
            args.suite or "gen-m8a",
            "M8 defined-name and 3-D reference probes from rustsheet-gen --policy names-3d; expectations from the Excel oracle",
            "M8",
            generate_names_3d(args.seed),
        )
        return
    catalog = Catalog.load(args.catalog or root / "eval" / "catalog" / "functions.yaml")
    specs = [
        generate_case(
            catalog,
            args.seed * 1_000_003 + i,
            milestone=args.milestone,
            formulas=args.formulas,
            max_depth=args.depth,
        )
        for i in range(args.count)
    ]
    write_suite(
        root,
        args.suite or f"gen-{args.milestone.lower()}",
        f"Synthetic cases generated by rustsheet-gen (milestone {args.milestone}); expectations from the Excel oracle",
        args.milestone,
        specs,
    )


if __name__ == "__main__":
    main()
