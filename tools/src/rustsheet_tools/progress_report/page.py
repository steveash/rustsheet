"""docs/progress.md: the page layout, the `status` and `method` blocks (SPEC-0022, T-0070), and
the stale page of an incomplete run (T-0071).

The `parity` block is parity.py's (T-0081); `since-last-run` and `trends` are history.py's
(T-0071); `goals` and `campaign` are goals.py's (T-0072); `top-functions` and `evidence` are
evidence.py's (T-0073); `arguments` is arguments.py's (T-0077); `codebase` is codebase.py's (T-0078). Later sections are
added by their own tasks as generated blocks in `LAYOUT`, without changing the block protocol in blocks.py.
"""

from __future__ import annotations

from pathlib import Path

from rustsheet_tools.progress_report import blocks, evidence, goals, history, parity
from rustsheet_tools.progress_report.markdown import REGENERATE, md_text
from rustsheet_tools.progress_report.model import Parity, ProgressReportError, Run

PAGE = "progress.md"
# The page's blocks in order (SPEC-0022 "Page layout"): (kind, name, heading). A generated block
# writes its own headings; a judgment block's heading is written above its markers.
LAYOUT = (
    (blocks.GENERATED, "status", None),
    (blocks.JUDGMENT, "bottom-line", "Bottom line"),
    (blocks.GENERATED, "goals", None),
    (blocks.GENERATED, "campaign", None),
    (blocks.GENERATED, "since-last-run", None),
    (blocks.GENERATED, "trends", None),
    (blocks.GENERATED, "parity", None),
    (blocks.GENERATED, "top-functions", None),
    (blocks.GENERATED, "evidence", None),
    (blocks.GENERATED, "arguments", None),
    (blocks.GENERATED, "codebase", None),
    (blocks.JUDGMENT, "readiness", "Real-world readiness"),
    (blocks.JUDGMENT, "risks", "Risks"),
    (blocks.GENERATED, "method", None),
)
GENERATED_BLOCKS = tuple(name for kind, name, _ in LAYOUT if kind == blocks.GENERATED)
JUDGMENT_BLOCKS = tuple(name for kind, name, _ in LAYOUT if kind == blocks.JUDGMENT)
HEADER = (
    f"<!-- Generated by `{REGENERATE}` (tools/src/rustsheet_tools/progress_report/). "
    "Edit only the text inside the judgment blocks. -->\n# RustSheet progress"
)


def _list(items: list[str]) -> str:
    return ", ".join(items) if items else "none"


LINKS = """- The steward's operational log is [docs/status.md](status.md). Every function's parity is in
  [docs/progress/functions.md](progress/functions.md)."""


def _commit(commit: str | None) -> str:
    return f"commit `{commit}`" if commit else "an unknown commit (git was unavailable)"


def _suites(run: Run) -> str:
    ran = [md_text(name) for name in run.suites]
    skipped = [f"{md_text(s.name)} ({md_text(s.reason)})" for s in run.skipped]
    return f"""- **Suites run ({len(ran)}):** {_list(ran)}.
- **Suites skipped ({len(skipped)}):** {_list(skipped)}."""


def same_commit(a: str, b: str) -> bool:
    """Whether two abbreviated shas name the same commit (one is a prefix of the other)."""
    return a.startswith(b) or b.startswith(a)


def status(run: Run) -> str:
    """The `status` block: the run's date and commit, the suites it ran and skipped, and links.
    It names only the report's commit, never the generating HEAD, so the same report gives the
    same block from any checkout."""
    lines = [
        f"The eval run of **{run.date}** at {_commit(run.commit)} (report.json `run`).",
        "",
        _suites(run),
        LINKS,
    ]
    return "\n".join(lines)


def stale_status(
    reason: str,
    date: str,
    commit: str | None,
    last: history.Row | None,
    run: Run | None,
    *,
    head: str | None,
) -> str:
    """The `status` block of an incomplete run: a Stale banner with `reason`, this run's date and
    commit, the commit generating the page (`head`) when that differs, and the last complete run
    (`last`, a history row) whose numbers the page still shows."""
    if last is None:
        shown = (
            f"No complete run is recorded in {history.HISTORY_LINK} yet, so the rest of the page is "
            "from before the history began, or empty."
        )
    else:
        shown = (
            f"Every number below is from the last complete run, **{last['date']}** at "
            f"{_commit(last['commit'])}."
        )
    at = _commit(commit)
    if head is not None and (commit is None or not same_commit(head, commit)):
        at += f", generated at commit `{head}`,"
    lines = [f"> **Stale.** The run of **{date}** at {at} is incomplete: {md_text(reason)}. {shown}"]
    if run is not None:
        lines += ["", _suites(run)]
    else:
        lines.append("")
    lines.append(LINKS)
    return "\n".join(lines)


METHOD = f"""## Method

- **Status.** The run date, commit and suites are the eval report's `run` record
  (eval/runs/latest/report.json, written by `make eval`): the UTC date, `git rev-parse --short=8
  HEAD`, and each suite under eval/suites that did not run, with the reason.
- **Judgment blocks.** The bottom line, readiness and risks are written by the steward between
  judgment markers. The generator copies their text unchanged on every run. Each starts with an
  as-of line naming the run it was written for; when that is not this run, a line under the
  heading says so, and the text is still shown.
- **One definition per measure.** Every verdict, bucket and tier is computed once, in the Rust eval
  report (crates/rustsheet-eval). This page only adds up the report's counts.
{goals.METHOD}
{parity.METHOD}
{history.METHOD}
- **Real-world calls.** report.json `functions[].real_world_calls` counts the formula cells of the
  Excel-saved corpora calipers and poi that call each function (`REAL_WORLD_SUITES` in
  crates/rustsheet-eval/src/report.rs). The parity line weights each function's attributed
  within-15-digit share by those calls; when either suite did not run it says so instead.
- **Argument coverage.** Each function's share is report.json `argument_coverage[].single`
  (crates/rustsheet-eval/src/argument_coverage.rs): of the argument classes its catalog
  parameters' modes expect by rule, those some Excel-evidence cell passes, a literal as written
  and a single-cell reference by the referenced cell's value. Indicative only.
- **Codebase health.** Counts read from quality/lint-debt.json (allow entries: the lints listed
  per manifest), quality/duplication.json (`duplicated_lines`), quality/oversized-files.json (one
  entry per file), quality/evidence-floor.json (`below_floor`), docs/decisions/0*.md (files) and
  docs/excel-semantics/*.md (lines). The change is against the last complete history row that has
  a `codebase` object.
- **Regenerate** with `{REGENERATE}`. The same inputs give a byte-identical page."""


def parse(text: str) -> dict[str, blocks.Block]:
    """The blocks of an existing page, checked against `LAYOUT`'s names."""
    return blocks.parse(text, GENERATED_BLOCKS, JUDGMENT_BLOCKS)


def render(run: Run, data: Parity, previous: str | None, sections: dict[str, str]) -> str:
    """The whole page for a complete `run`, keeping the judgment text of `previous` (the existing
    page). `sections` holds the goals, history, arguments and codebase blocks (`goals`,
    `campaign`, `since-last-run`, `trends`, `arguments`, `codebase`)."""
    old = parse(previous) if previous is not None else {}
    body = {
        **sections,
        **evidence.blocks(data),
        "status": status(run),
        "parity": parity.block(data),
        "method": METHOD,
    }
    parts = [HEADER]
    for _, name, heading in LAYOUT:
        parts.append(
            blocks.judgment(name, heading, old, run)
            if heading is not None
            else blocks.generated(name, body[name])
        )
    return "\n\n".join(parts) + "\n"


NO_COMPLETE_RUN = f"_No complete run yet: `{REGENERATE}` writes this block when the eval completes._"


def render_stale(previous: str | None, status_body: str) -> str:
    """The page of an incomplete run: `previous` with only its `status` block rewritten to
    `status_body`, every other byte kept. With no previous page, a page whose other generated
    blocks say no complete run has written them yet."""
    if previous is None:
        parts = [HEADER]
        for _, name, heading in LAYOUT:
            parts.append(
                blocks.judgment(name, heading, {}, None)
                if heading is not None
                else blocks.generated(name, status_body if name == "status" else NO_COMPLETE_RUN)
            )
        return "\n\n".join(parts) + "\n"
    old = parse(previous)
    if "status" not in old:
        msg = f"the existing {PAGE} has no status block to mark stale"
        raise ProgressReportError(msg)
    return blocks.replace_generated(previous, old["status"], status_body)


def read_existing(out_dir: Path) -> str | None:
    """The existing page under `out_dir`, exactly as stored, or None when there is none yet."""
    path = out_dir / PAGE
    try:
        raw = path.read_bytes()
    except FileNotFoundError:
        return None
    except OSError as e:
        msg = f"{path}: {e}"
        raise ProgressReportError(msg) from e
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError as e:
        msg = f"{path}: not UTF-8 ({e})"
        raise ProgressReportError(msg) from e


def write(out_dir: Path, text: str) -> Path:
    """Write the page under `out_dir` byte for byte (no newline translation); return its path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / PAGE
    path.write_bytes(text.encode("utf-8"))
    return path
