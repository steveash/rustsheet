    /// A run of `(case, visibly-off cells)`; a case whose id contains `new` is new to its
    /// suite's baseline.
    fn run(cases: &[(&str, usize)]) -> VisibleCount {
        VisibleCount {
            cases: cases
                .iter()
                .map(|(c, off)| {
                    let new_case = c.contains("new");
                    (
                        (*c).to_string(),
                        CaseCount {
                            off: *off,
                            new_case,
                        },
                    )
                })
                .collect(),
        }
    }

    fn lock(cases: &[(&str, usize)]) -> Lock {
        Lock {
            cases: cases.iter().map(|(c, n)| ((*c).to_string(), *n)).collect(),
        }
    }

    fn over(case: &str, off: usize, allowed: usize) -> Over {
        Over {
            case: case.into(),
            off,
            allowed,
        }
    }

    const PR: Update = Update {
        allow_regressions: false,
        lower: false,
    };
    const STEWARD: Update = Update {
        allow_regressions: false,
        lower: true,
    };
    const ALLOW: Update = Update {
        allow_regressions: true,
        lower: false,
    };

    /// `check` fails each case above its line, even when another case's drop leaves the total
    /// below the lock's: slack in one case no longer hides a rise in another (decision 0217).
    #[test]
    fn check_fails_a_rise_in_an_existing_case_whatever_the_total() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let j = judge(&l, &run(&[("p/a", 3), ("p/b", 5)]), None);
        assert!(j.holds());
        assert_eq!(j.record, None);
        assert!(judge(&l, &run(&[("p/a", 2), ("p/b", 1)]), None).holds());
        let j = judge(&l, &run(&[("p/a", 4), ("p/b", 0)]), None);
        assert_eq!(j.over, vec![over("p/a", 4, 3)]);
        assert_eq!(j.record, None);
    }

    /// A case with no line allows none, so `check` fails a new case with visibly-off cells
    /// until `update-baseline` records its line; a new case with none needs no line.
    #[test]
    fn check_fails_a_new_case_without_a_line() {
        let l = lock(&[("p/a", 3)]);
        let j = judge(&l, &run(&[("p/a", 3), ("p/new", 2)]), None);
        assert_eq!(j.over, vec![over("p/new", 2, 0)]);
        assert!(judge(&l, &run(&[("p/a", 3), ("p/new", 0)]), None).holds());
    }

    /// `update-baseline` records a new case's line, adding nothing else: the other lines, and
    /// the slack below them, stay as they were.
    #[test]
    fn update_records_a_new_case() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let j = judge(&l, &run(&[("p/a", 1), ("p/b", 5), ("p/new", 2)]), Some(PR));
        assert!(j.holds());
        assert_eq!(
            j.record,
            Some(lock(&[("p/a", 3), ("p/b", 5), ("p/new", 2)]))
        );
    }

    /// An existing case is raised only with `--allow-regressions`, the steward's lowering
    /// included; a refused rise writes nothing.
    #[test]
    fn update_raises_an_existing_case_only_with_allow_regressions() {
        let l = lock(&[("p/a", 3)]);
        for u in [PR, STEWARD] {
            let j = judge(&l, &run(&[("p/a", 4), ("p/new", 2)]), Some(u));
            assert_eq!(j.over, vec![over("p/a", 4, 3)]);
            assert_eq!(j.record, None);
        }
        let j = judge(&l, &run(&[("p/a", 4), ("p/b", 1)]), Some(ALLOW));
        assert!(j.holds());
        assert_eq!(j.record, Some(lock(&[("p/a", 4), ("p/b", 1)])));
    }

    /// A PR's update leaves a drop as slack, so fix PRs leave the lock out of their diff
    /// (decision 0093); `--lower-visible-lock` lowers it and drops the line at 0.
    #[test]
    fn update_lowers_only_with_the_flag() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let fixed = run(&[("p/a", 0), ("p/b", 2)]);
        let j = judge(&l, &fixed, Some(PR));
        assert!(j.holds());
        assert_eq!(j.record, None);
        assert_eq!(judge(&l, &fixed, Some(ALLOW)).record, None);
        let j = judge(&l, &fixed, Some(STEWARD));
        assert_eq!(j.record, Some(lock(&[("p/b", 2)])));
    }

    /// With `--new-cases`, only the listed cases are new (decision 0217): after a catch-up
    /// merge, an unlisted case without a line or with a rise is refused even when the tree's
    /// baseline lacks it, and a listed case's line is written whatever its count.
    #[test]
    fn new_cases_list_alone_decides_what_is_new() {
        let listed: BTreeSet<String> = ["p/pr-added".to_string()].into();
        assert!(is_new_case(Some(&listed), true, "p/pr-added"));
        assert!(!is_new_case(Some(&listed), false, "p/main-case"));
        assert!(is_new_case(None, false, "p/main-case"));
        assert!(!is_new_case(None, true, "p/main-case"));
        let l = lock(&[("p/a", 3)]);
        let count = |cases: &[(&str, usize)]| VisibleCount {
            cases: cases
                .iter()
                .map(|(c, off)| {
                    let in_baseline = !c.contains("absent");
                    let new_case = is_new_case(Some(&listed), in_baseline, c);
                    (
                        (*c).to_string(),
                        CaseCount {
                            off: *off,
                            new_case,
                        },
                    )
                })
                .collect(),
        };
        let j = judge(&l, &count(&[("p/a", 3), ("p/pr-added", 7)]), Some(PR));
        assert!(j.holds());
        assert_eq!(j.record, Some(lock(&[("p/a", 3), ("p/pr-added", 7)])));
        let j = judge(
            &l,
            &count(&[("p/a", 4), ("p/main-absent", 2), ("p/pr-added", 7)]),
            Some(PR),
        );
        assert_eq!(j.over, vec![over("p/a", 4, 3), over("p/main-absent", 2, 0)]);
        assert_eq!(j.record, None);
    }

    /// `--new-cases` entries name cases by id or by repository-relative case file path, `..`
