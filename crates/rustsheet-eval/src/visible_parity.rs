//! The visible-parity ratchet (T-0061, decisions 0088, 0093 and 0217): no case of the vendored
//! gated suites may have more in-scope cells visibly off from Excel (decision 0083) than its line
//! in [`LOCK_PATH`] allows. `rustsheet-eval check` holds a full gated run to the lock with
//! [`judge`]. `update-baseline` records the line of a case new to its suite's baseline, raises an
//! existing case only with `--allow-regressions`, and lowers one only with
//! `--lower-visible-lock` (the steward, daily). One line per case, like the known-failure lists,
//! so parallel PRs that add or fix different cases merge cleanly (T-3544, decision 0217).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use crate::catalog::Catalog;
use crate::closeness::{self, Visible};
use crate::formula_calls::{calls_only_in_scope, functions_in};
pub use crate::lock_file::LockError;
use crate::report::{FunctionStat, RunReport};
use crate::runner::CaseResult;

/// The committed lock, relative to the repository root. It sits with the baselines because
/// `make eval-baseline` records it with them, and like them it is never hand-edited.
pub const LOCK_PATH: &str = "eval/baseline/visible-parity.txt";

const HEADER: &str = "# RustSheet visible-parity lock (decisions 0088, 0093, 0217). Generated by `rustsheet-eval\n\
# update-baseline`; never edit by hand. `case<TAB>n`: at most n in-scope cells of the case may be\n\
# visibly off from Excel. A case with no line allows none. Only `--lower-visible-lock` lowers a line.\n";

/// The committed lock: case id → the visibly-off in-scope cells it may have. Cases with none
/// have no line.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lock {
    /// Case id (`<suite>/<case>`) → allowed visibly-off in-scope cells, every one above 0.
    pub cases: BTreeMap<String, usize>,
}

impl Lock {
    /// The visibly-off cells `case` may have: its line's count, or 0 without a line.
    #[must_use]
    pub fn allowed(&self, case: &str) -> usize {
        self.cases.get(case).copied().unwrap_or(0)
    }

    /// The visibly-off cells all cases together may have.
    #[must_use]
    pub fn total(&self) -> usize {
        self.cases.values().sum()
    }

    /// Parses the lock's text.
    ///
    /// # Errors
    /// The 1-based number of the first line that is not a comment, a blank line or
    /// `case<TAB>count`, or that repeats a case.
    pub fn parse(text: &str) -> Result<Lock, usize> {
        let mut lock = Lock::default();
        for (n, line) in text.lines().enumerate() {
            if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            let parsed = line
                .split_once('\t')
                .and_then(|(case, count)| Some((case, count.parse::<usize>().ok()?)));
            match parsed {
                Some((case, count)) if !case.is_empty() && !lock.cases.contains_key(case) => {
                    lock.cases.insert(case.to_string(), count);
                }
                _ => return Err(n + 1),
            }
        }
        Ok(lock)
    }

    /// The lock's text: the header, then one sorted line per case with a count above 0.
    #[must_use]
    pub fn render(&self) -> String {
        let mut out = String::from(HEADER);
        for (case, count) in self.cases.iter().filter(|(_, n)| **n > 0) {
            let _ = writeln!(out, "{case}\t{count}");
        }
        out
    }

    /// Reads [`LOCK_PATH`] under `root`. A missing lock allows no visibly-off cell.
    ///
    /// # Errors
    /// When the file cannot be read or is malformed.
    pub fn read(root: &Path) -> Result<Lock, LockError> {
        let path = root.join(LOCK_PATH);
        match std::fs::read_to_string(&path) {
            Ok(text) => Lock::parse(&text).map_err(|line| LockError::Line {
                path: LOCK_PATH,
                line,
            }),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Lock::default()),
            Err(source) => Err(LockError::Io { path, source }),
        }
    }

    /// Writes the lock to [`LOCK_PATH`] under `root`.
    ///
    /// # Errors
    /// When the file cannot be written.
    pub fn write(&self, root: &Path) -> Result<(), LockError> {
        let path = root.join(LOCK_PATH);
        std::fs::write(&path, self.render()).map_err(|source| LockError::Io { path, source })
    }
}

/// One case's visibly-off in-scope cells in a run.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct CaseCount {
    /// Visibly-off cells that call no out-of-scope function.
    pub off: usize,
    /// Whether the case is new: its suite's committed baseline does not list it, so
    /// `update-baseline` records its line whatever the count.
    pub new_case: bool,
}

/// The visibly-off in-scope cells of a run, per case, for every case of the vendored gated
/// suites the run checked (cases with none included, so a removed case is told apart).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct VisibleCount {
    /// Case id → its count.
    pub cases: BTreeMap<String, CaseCount>,
}

impl VisibleCount {
    /// Counts `case`'s visibly-off cells that call no out-of-scope function; `new_case` when the
    /// committed baseline does not list the case.
    pub fn add(&mut self, catalog: &Catalog, case: &CaseResult, new_case: bool) {
        let off = case
            .cells
            .iter()
            .filter(|c| Visible::is_off(c))
            .filter(|c| {
                let called = c.formula.as_deref().map(functions_in).unwrap_or_default();
                calls_only_in_scope(catalog, &called)
            })
            .count();
        self.cases
            .insert(case.id.clone(), CaseCount { off, new_case });
    }

    /// Every visibly-off in-scope cell.
    #[must_use]
    pub fn cells(&self) -> usize {
        self.cases.values().map(|c| c.off).sum()
    }

    /// The visibly-off in-scope cells of new cases.
    #[must_use]
    pub fn new_coverage(&self) -> usize {
        self.cases
            .values()
            .filter(|c| c.new_case)
            .map(|c| c.off)
            .sum()
    }
}

/// How `update-baseline` may move the lock.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Update {
    /// `--allow-regressions`: raise any case (needs a decision record).
    pub allow_regressions: bool,
    /// `--lower-visible-lock`: lower cases and drop their lines at 0 (the steward's daily run,
    /// decision 0093).
    pub lower: bool,
}

/// A case with more visibly-off cells than its line allows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Over {
    /// The case id.
    pub case: String,
    /// Its visibly-off in-scope cells in the run.
    pub off: usize,
    /// What its line allows (0 without one).
    pub allowed: usize,
}

/// What the gate decided about a run.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Judgement {
    /// The cases over their lines; the gate fails when there is one.
    pub over: Vec<Over>,
    /// The lock to write (`update-baseline` only, and only when it changes and no case is over).
    pub record: Option<Lock>,
}

impl Judgement {
    /// Whether the gate passes.
    #[must_use]
    pub fn holds(&self) -> bool {
        self.over.is_empty()
    }
}

/// Judges each case of `count` against its line in `lock`. `update` is `None` for `check`, which
/// fails only a case above its line (a case with no line allows 0, so a new case's line must be
/// recorded). For `update-baseline` it records a new case's line whatever its count, raises an
/// existing case only with `--allow-regressions`, lowers one only with `--lower-visible-lock`
/// (otherwise the drop is slack, decision 0093), and drops the lines of cases the run no longer
/// has.
#[must_use]
pub fn judge(lock: &Lock, count: &VisibleCount, update: Option<Update>) -> Judgement {
    let mut next = Lock::default();
    let mut over = Vec::new();
    for (case, c) in &count.cases {
        let allowed = lock.allowed(case);
        let kept = match update {
            _ if c.off == allowed => allowed,
            Some(u) if c.off < allowed && u.lower => c.off,
            _ if c.off < allowed => allowed,
            Some(u) if u.allow_regressions || c.new_case => c.off,
            None | Some(_) => {
                over.push(Over {
                    case: case.clone(),
                    off: c.off,
                    allowed,
                });
                allowed
            }
        };
        if kept > 0 {
            next.cases.insert(case.clone(), kept);
        }
    }
    let record = (update.is_some() && over.is_empty() && next != *lock).then_some(next);
    Judgement { over, record }
}
/// The report's visibly-off section: cells per suite, then the functions they are blamed on,
/// worst first (decision 0083).
pub fn write_markdown(report: &RunReport, md: &mut String) {
    let _ = writeln!(md, "\n## Visibly off (fifteen digits)\n");
    let _ = writeln!(
        md,
        "{} in-scope cells are visibly off: a number further than half a unit in the 15th significant digit of Excel's (or 0 against nonzero), or a wrong type, error, text or boolean. `digits15` cells are within that half unit but more than 4 ulp away.\n",
        report.visibly_off_cells()
    );
    let _ = writeln!(
        md,
        "| suite | scored | bit-exact | ≤4 ulp | digits15 | visible numeric | visible other |"
    );
    let _ = writeln!(md, "|---|---|---|---|---|---|---|");
    for s in &report.suites {
        let c = &s.closeness;
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} |",
            s.name,
            c.scored(),
            c.pass,
            c.ulp1 + c.ulp4,
            c.digits15,
            c.visible_numeric,
            c.visible_other
        );
    }
    let mut off: Vec<&FunctionStat> = report
        .functions
        .iter()
        .filter(|f| f.visible.total() > 0)
        .collect();
    off.sort_by(|a, b| {
        b.visible
            .total()
            .cmp(&a.visible.total())
            .then_with(|| a.name.cmp(&b.name))
    });
    let _ = writeln!(
        md,
        "\nFunctions with visibly-off cells ({}), worst first. A cell is blamed on the functions it calls other than glue ({}), or on its glue when it calls nothing else:\n",
        off.len(),
        closeness::GLUE.join(", ")
    );
    let _ = writeln!(md, "| function | visibly off | numeric | other | checked |");
    let _ = writeln!(md, "|---|---|---|---|---|");
    for f in off {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} |",
            f.name,
            f.visible.total(),
            f.visible.numeric,
            f.visible.other,
            f.cells
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::report::tests::{case, cell};
    use crate::runner::CellResult;
    use crate::value::{Value, Verdict};

    /// A run of `(case, visibly-off cells)`; a case whose id contains `new` is new to its
    /// suite's baseline.
    fn run(cases: &[(&str, usize)]) -> VisibleCount {
        VisibleCount {
            cases: cases
                .iter()
                .map(|(c, off)| {
                    let new_case = c.contains("new");
                    (
                        (*c).to_string(),
                        CaseCount {
                            off: *off,
                            new_case,
                        },
                    )
                })
                .collect(),
        }
    }

    fn lock(cases: &[(&str, usize)]) -> Lock {
        Lock {
            cases: cases.iter().map(|(c, n)| ((*c).to_string(), *n)).collect(),
        }
    }

    fn over(case: &str, off: usize, allowed: usize) -> Over {
        Over {
            case: case.into(),
            off,
            allowed,
        }
    }

    const PR: Update = Update {
        allow_regressions: false,
        lower: false,
    };
    const STEWARD: Update = Update {
        allow_regressions: false,
        lower: true,
    };
    const ALLOW: Update = Update {
        allow_regressions: true,
        lower: false,
    };

    /// `check` fails each case above its line, even when another case's drop leaves the total
    /// below the lock's: slack in one case no longer hides a rise in another (decision 0217).
    #[test]
    fn check_fails_a_rise_in_an_existing_case_whatever_the_total() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let j = judge(&l, &run(&[("p/a", 3), ("p/b", 5)]), None);
        assert!(j.holds());
        assert_eq!(j.record, None);
        assert!(judge(&l, &run(&[("p/a", 2), ("p/b", 1)]), None).holds());
        let j = judge(&l, &run(&[("p/a", 4), ("p/b", 0)]), None);
        assert_eq!(j.over, vec![over("p/a", 4, 3)]);
        assert_eq!(j.record, None);
    }

    /// A case with no line allows none, so `check` fails a new case with visibly-off cells
    /// until `update-baseline` records its line; a new case with none needs no line.
    #[test]
    fn check_fails_a_new_case_without_a_line() {
        let l = lock(&[("p/a", 3)]);
        let j = judge(&l, &run(&[("p/a", 3), ("p/new", 2)]), None);
        assert_eq!(j.over, vec![over("p/new", 2, 0)]);
        assert!(judge(&l, &run(&[("p/a", 3), ("p/new", 0)]), None).holds());
    }

    /// `update-baseline` records a new case's line, adding nothing else: the other lines, and
    /// the slack below them, stay as they were.
    #[test]
    fn update_records_a_new_case() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let j = judge(&l, &run(&[("p/a", 1), ("p/b", 5), ("p/new", 2)]), Some(PR));
        assert!(j.holds());
        assert_eq!(
            j.record,
            Some(lock(&[("p/a", 3), ("p/b", 5), ("p/new", 2)]))
        );
    }

    /// An existing case is raised only with `--allow-regressions`, the steward's lowering
    /// included; a refused rise writes nothing.
    #[test]
    fn update_raises_an_existing_case_only_with_allow_regressions() {
        let l = lock(&[("p/a", 3)]);
        for u in [PR, STEWARD] {
            let j = judge(&l, &run(&[("p/a", 4), ("p/new", 2)]), Some(u));
            assert_eq!(j.over, vec![over("p/a", 4, 3)]);
            assert_eq!(j.record, None);
        }
        let j = judge(&l, &run(&[("p/a", 4), ("p/b", 1)]), Some(ALLOW));
        assert!(j.holds());
        assert_eq!(j.record, Some(lock(&[("p/a", 4), ("p/b", 1)])));
    }

    /// A PR's update leaves a drop as slack, so fix PRs leave the lock out of their diff
    /// (decision 0093); `--lower-visible-lock` lowers it and drops the line at 0.
    #[test]
    fn update_lowers_only_with_the_flag() {
        let l = lock(&[("p/a", 3), ("p/b", 5)]);
        let fixed = run(&[("p/a", 0), ("p/b", 2)]);
        let j = judge(&l, &fixed, Some(PR));
        assert!(j.holds());
        assert_eq!(j.record, None);
        assert_eq!(judge(&l, &fixed, Some(ALLOW)).record, None);
        let j = judge(&l, &fixed, Some(STEWARD));
        assert_eq!(j.record, Some(lock(&[("p/b", 2)])));
    }

    /// The lines of cases the run no longer has go with the case; `check` ignores them, since
    /// the suite's baseline already fails a removed case.
    #[test]
    fn a_removed_case_loses_its_line_on_update() {
        let l = lock(&[("p/a", 3), ("p/gone", 5)]);
        let now = run(&[("p/a", 3)]);
        assert!(judge(&l, &now, None).holds());
        assert_eq!(judge(&l, &now, Some(PR)).record, Some(lock(&[("p/a", 3)])));
    }

    /// One sorted line per case with cells off and no total, so PRs that touch different cases
    /// change different lines and merge cleanly; text round-trips.
    #[test]
    fn the_lock_is_one_sorted_line_per_case() {
        let l = lock(&[("probes/b.case.json", 2), ("gen-m2/x", 7), ("probes/z", 0)]);
        let text = l.render();
        let lines: Vec<&str> = text.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(lines, ["gen-m2/x\t7", "probes/b.case.json\t2"]);
        assert_eq!(
            Lock::parse(&text),
            Ok(lock(&[("probes/b.case.json", 2), ("gen-m2/x", 7)]))
        );
        assert_eq!(l.total(), 9);
        assert_eq!(l.allowed("probes/none"), 0);
        assert_eq!(Lock::parse("# c\n\np/a\t1\np/a\t2\n"), Err(4));
        assert_eq!(Lock::parse("p/a 1\n"), Err(1));
        assert_eq!(Lock::parse("p/a\t-1\n"), Err(1));
        assert_eq!(Lock::parse("\t1\n"), Err(1));
    }

    #[test]
    fn the_committed_lock_parses_and_is_in_canonical_form() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let committed = Lock::read(&root).unwrap();
        let text = std::fs::read_to_string(root.join(LOCK_PATH)).unwrap();
        assert_eq!(committed.render(), text);
    }
    /// Visibly-off cells are blamed on the specialised function, not on the glue around it, and
    /// each suite counts its in-scope visibly-off cells for the ratchet (T-0061).
    #[test]
    fn visibly_off_cells_are_blamed_past_glue_and_counted_per_suite() {
        let mut r = case("probes/a", 1);
        let off = |formula: &str| CellResult {
            actual: Value::Number(2.0),
            ..cell(formula, Verdict::NumericMismatch)
        };
        r.cells = vec![
            off("IF(TRUE,GAMMA(10))"),
            off("SUM(1,2)"),
            cell("WEBSERVICE(\"x\")", Verdict::TypeMismatch),
            cell("GAMMA(2)", Verdict::Pass),
        ];
        let catalog = Catalog::from_functions([crate::catalog::CatalogFunction {
            name: "WEBSERVICE".into(),
            category: "web".into(),
            milestone: "M5".into(),
            scope: crate::catalog::Scope::Out,
            reason: None,
            oracle: None,
            v15: None,
            v15_reason: None,
            returns: None,
            params: Vec::new(),
        }]);
        let report = RunReport::build("e", &[r], &[], &catalog);
        let visible = |name: &str| {
            report
                .functions
                .iter()
                .find(|f| f.name == name)
                .map(|f| f.visible.total())
        };
        assert_eq!(visible("GAMMA"), Some(1));
        assert_eq!(visible("IF"), Some(0));
        assert_eq!(visible("SUM"), Some(1));
        assert_eq!(report.suites[0].closeness.scored(), 3);
        assert_eq!(report.visibly_off_cells(), 2);
        let md = report.to_markdown(1);
        assert!(md.contains("2 in-scope cells are visibly off"), "{md}");
        assert!(md.contains("| GAMMA | 1 | 1 | 0 | 2 |"), "{md}");
    }
}
