//! Tables of Excel's text collation (`collation.rs`): the diacritic weights of the combining
//! marks and the canonical decompositions of the accented letters.

/// The diacritic weight each combining mark U+0300 to U+0362 adds to the letter before it, from
/// Microsoft's Windows sorting weight table (`Windows Server 2022 Sorting Weight Table.txt`,
/// default table, the DW column of the script-member-1 "non-spacing" rows; U+034F, the combining
/// grapheme joiner, has no weight). A letter has diacritic weight 2 and each mark adds its weight,
/// wrapping past 255: `"a"&UNICHAR(769)&UNICHAR(769)` (2 + 12 + 12) equals `"å"` (2 + 24), and
/// two U+0342 (2 + 141 + 141 = 284, so 28) equal one U+0327 (2 + 26)
