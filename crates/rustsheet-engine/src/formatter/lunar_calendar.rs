/// The lunar year, month (1-14, counting a leap month) and day of 1900-system `serial`, or `None`
/// where Excel shows `#VALUE!` (serial 60, the fictitious 1900-02-29, and negative serials) and
/// past the tables. Serial 0 reads as serial 1 (`[$-110409]d` of both is "16").
pub(crate) fn lunar_ymd(serial: i64, table: LunarTable) -> Option<(i32, u32, u32)> {
    let day = match serial {
        0 => 1,
        1..=59 => serial,
        61.. => serial - 1,
        _ => return None,
    };
    if day > LAST_DAY {
        return None;
    }
    let lengths: &[u8] = match table {
        LunarTable::Chinese => &CHINESE,
        LunarTable::Eastern => &EASTERN,
    };
    let (mut year, mut month, mut start) = (FIRST_YEAR, FIRST_MONTH, FIRST_MONTH_START);
    for &entry in lengths {
        let next = start + i64::from(entry & LENGTH);
        if day < next {
            break;
        }
        start = next;
        if entry & NEW_YEAR == 0 {
            month += 1;
        } else {
            (year, month) = (year + 1, 1);
        }
    }
    if EARLY_YEARS
        .iter()
        .any(|(first, last)| (*first..=*last).contains(&day))
    {
        year += 1;
    }
    let day_of_month = u32::try_from(day - start + 1).ok()?;
    Some((year, month, day_of_month))
}

#[cfg(test)]
mod tests {
    use super::{lunar_ymd, LunarTable};

    #[test]
    fn lunar_dates_of_the_probes() {
        // probes/text-locale-lunar-edges A1-A29, text-locale-calendars A98-A115,
        // text-locale-lunar-tokens A1-A9, A61-A74.
        for (serial, ymd) in [
            (0, (1899, 12, 16)),
            (1, (1899, 12, 16)),
            (30, (1899, 13, 15)),
            (59, (1900, 1, 14)),
            (61, (1900, 1, 15)),
            (415, (1901, 1, 15)),
            (17940, (1948, 14, 1)),
            (17941, (1949, 1, 1)),
            (44948, (2023, 1, 1)),
            (45000, (2023, 2, 24)),
            (45007, (2023, 3, 1)),
            (45302, (2023, 13, 1)),
            (45332, (2024, 1, 1)),
            (73415, (2100, 12, 16)),
        ] {
            assert_eq!(
                lunar_ymd(serial, LunarTable::Chinese),
                Some(ymd),
                "{serial}"
            );
        }
        assert_eq!(lunar_ymd(45065, LunarTable::Chinese), Some((2023, 5, 1)));
        assert_eq!(lunar_ymd(45065, LunarTable::Eastern), Some((2023, 4, 30)));
        assert_eq!(lunar_ymd(45066, LunarTable::Eastern), Some((2023, 5, 1)));
        // The year turns on 1960-01-01, not at month 1 (text-locale-lunar-tokens A82).
        assert_eq!(lunar_ymd(21915, LunarTable::Chinese), Some((1959, 12, 18)));
        assert_eq!(lunar_ymd(21916, LunarTable::Chinese), Some((1960, 12, 19)));
        assert_eq!(lunar_ymd(21943, LunarTable::Chinese), Some((1960, 1, 1)));
        assert_eq!(lunar_ymd(60, LunarTable::Chinese), None);
        assert_eq!(lunar_ymd(-1, LunarTable::Chinese), None);
        assert_eq!(lunar_ymd(73416, LunarTable::Chinese), None);
    }
}
