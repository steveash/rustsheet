import mpmath as mp
mp.mp.dps=40
def Acody(P,Q,Dc,t):
    xn=mp.mpf(0); xd=mp.mpf(1)
    for i in range(8): xn=xn*t+P[i]; xd=xd*t+Q[i]
    return Dc+t*xn/xd
