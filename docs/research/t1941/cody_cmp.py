def cody(P,Q,Dc,shift):
    num=np.array(P)          # descending in t, degree 7
    den=np.concatenate([[1.0],Q])  # descending, degree 8
    N=np.polyadd(Dc*den, np.concatenate([num,[0.0]]))  # D*den + t*num
    print(' A num roots (x):',np.sort(np.roots(N)+shift))
    print(' A den roots (x):',np.sort(np.roots(den)+shift))
