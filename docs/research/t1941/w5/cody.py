# Cody ALGAMA near-1 form A = D1 + t*xnum/xden (t = x-1); Taylor invariants at x=0 (t=-1).
import mpmath as mp
mp.mp.dps=40
D1=mp.mpf('-5.772156649015328605195174e-1')
P1=[mp.mpf(v) for v in '4.945235359296727046734888e0 2.018112620856775083915565e2 2.290838373831346393026739e3 1.131967205903380828685045e4 2.855724635671635335736389e4 3.848496228443793359990269e4 2.637748787624195437963534e4 7.225813979700288197698961e3'.split()]
Q1=[mp.mpf(v) for v in '6.748212550303777196073036e1 1.113332393857199323513008e3 7.738757056935398733233834e3 2.763987074403340708898585e4 5.499310206226157329794414e4 6.161122180066002127833352e4 3.635127591501940507276287e4 8.785536302431013170870835e3'.split()]
def A(x):
    t=x-1; xn=mp.mpf(0); xd=mp.mpf(1)
    for p,q in zip(P1,Q1): xn=xn*t+p; xd=xd*t+q
    return D1+t*xn/xd
print('taylor at 0:', [mp.nstr(mp.diff(A,0,k)/mp.factorial(k),14) for k in range(4)])
for x in [0.7,0.8,1.0001,1.2,1.5]:
    x=mp.mpf(x); print(float(x), mp.nstr(A(x)/(mp.loggamma(x)/(x-1))-1,5))
