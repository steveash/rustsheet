"""T-3350 fresh sweep (decision 0188 R2, R4.2): CHISQ.INV and CHISQ.INV.RT points drawn log-uniform
over the valid domain and stratified around the failing region (df 5E6 to 1E8, where the engine was
#NUM!), scored against Excel (the oracle sidecar) and a 50-digit mpmath reference.

    python sweep.py generate CASE.json          # write the case (deterministic, seed below)
    python sweep.py score CASE.json SHOW.txt    # SHOW.txt: `rustsheet-eval show <case>` output

Strata, per function (120 points each):
- full (40): df log-uniform over [1, 1E10]; p log-uniform over [1E-300, 0.5] or 1 - p
  log-uniform over [1E-15, 0.5], each side with probability 1/2.
- region (50): df log-uniform over [1E6, 1E9], p drawn as in full.
- region-near-1 (30): df log-uniform over [1E6, 1E9], p = 1 - 10^-u, u uniform in [1, 15].
p is written with at most 15 significant digits and the math is at the double nearest that literal.
Needs mpmath (not a dependency of tools/).
"""

from __future__ import annotations

import json
import random
import re
import sys
import time
from collections import Counter

FUNCTIONS = ("CHISQ.INV", "CHISQ.INV.RT")
SEED = 3350
STRATA = (
    ("full", 40, 0.0, 10.0, False),
    ("region", 50, 6.0, 9.0, False),
    ("region-near-1", 30, 6.0, 9.0, True),
)


def literal(x: float) -> str:
    return f"{float(f'{x:.15g}'):.15g}".upper().replace("E-0", "E-").replace("E+", "E")


def draw_p(rng: random.Random, near_one: bool) -> float:
    if near_one:
        return 1.0 - 10.0 ** -rng.uniform(1.0, 15.0)
    # 1 - p is a 15-digit literal's distance from 1 only from 1E-15 on.
    if rng.random() < 0.5:
        return 10.0 ** rng.uniform(-300.0, -0.30103)
    return 1.0 - 10.0 ** rng.uniform(-15.0, -0.30103)


def generate(path: str) -> None:
    rng = random.Random(SEED)
    cells: dict[str, str] = {}
    hypotheses: dict[str, str] = {}
    row = 1
    for function in FUNCTIONS:
        for name, count, lo, hi, near_one in STRATA:
            for _ in range(count):
                df = max(1, round(10.0 ** rng.uniform(lo, hi)))
                p = draw_p(rng, near_one)
                text = literal(p)
                if float(text) in (0.0, 1.0):
                    text = literal(0.5)
                cells[f"A{row}"] = f"={function}({text},{df})"
                hypotheses[f"Calc!A{row}"] = f"t3350/{name}"
                row += 1
    case = {
        "format": "rustsheet-case/v1",
        "description": (
            "T-3350 fresh sweep (decision 0188 R4.2): CHISQ.INV and CHISQ.INV.RT log-uniform over df 1 to 1E10 "
            "and stratified around the failing region (df 1E6 to 1E9, p near 1); generated by "
            "docs/research/t3350/sweep.py, scored against Excel and 50-digit mpmath."
        ),
        "tags": ["M9", "probe", "statistics", "T-3350", "sweep", "incomplete-gamma"],
        "sheets": [{"name": "Calc", "cells": cells}],
        "hypotheses": hypotheses,
        "expected": {},
    }
    with open(path, "w") as out:
        json.dump(case, out, indent=1)
        out.write("\n")


def math_quantile(function: str, p_double: float, df: int) -> object:
    import mpmath as mp  # noqa: PLC0415

    mp.mp.dps = 60
    a = mp.mpf(df) / 2
    p = mp.mpf(p_double)
    lower_given = function == "CHISQ.INV"
    # The smaller tail and its exact probability (1 - p is exact for a double p of 1/2 or more).
    half = mp.mpf("0.5")
    use_lower = (p <= half) if lower_given else (p >= half)
    target = p if (p <= half) else 1 - p

    def continued_fraction_q(x: object) -> object:
        # Q(a, x) for x > a + 1: Legendre's continued fraction (modified Lentz).
        tiny = mp.mpf(10) ** -400
        b = x + 1 - a
        c = 1 / tiny
        d = 1 / b
        h = d
        i = 1
        while True:
            an = -i * (i - a)
            b += 2
            d = an * d + b
            d = tiny if d == 0 else d
            c = b + an / c
            c = tiny if c == 0 else c
            d = 1 / d
            delta = d * c
            h *= delta
            if abs(delta - 1) < mp.mpf(10) ** -58:
                break
            i += 1
        return mp.exp(a * mp.log(x) - x - mp.loggamma(a)) * h

    def lower_tail(x: object) -> object:
        # P(a, x) = x^a e^-x / Gamma(a + 1) * 1F1(1; a + 1; x) up to a + 1, else 1 - Q.
        x = mp.mpf(x)
        if x > a + 1:
            return 1 - continued_fraction_q(x)
        return mp.exp(a * mp.log(x) - x - mp.loggamma(a + 1)) * mp.hyp1f1(1, a + 1, x, maxterms=10**9)

    def upper_tail(x: object) -> object:
        # Q(a, x): for x > a + 1 Legendre's continued fraction (modified Lentz) at the working
        # precision, else 1 - P with the digits a Q near the target needs.
        x = mp.mpf(x)
        if x > a + 1:
            return continued_fraction_q(x)
        with mp.workdps(70 + max(0, int(-mp.log10(target)))):
            return +(1 - lower_tail(x))

    tail = lower_tail if use_lower else upper_tail

    def f(t: object) -> object:
        value = tail(mp.exp(t))
        return (mp.log(value) if value > 0 else mp.mpf(-10) ** 6) - mp.log(target)

    # f rises with log x for the lower tail and falls for the upper. Bracket in log x around the
    # Wilson-Hilferty start.
    sign = 1 if use_lower else -1
    z = mp.sqrt(2 * abs(mp.log(target)))
    z = -z if use_lower else z
    cube = 1 - mp.mpf(2) / (9 * df) + z * mp.sqrt(mp.mpf(2) / (9 * df))
    t0 = mp.log(a * cube**3) if cube > 0 else mp.log(a) - 10
    step = mp.mpf("0.01")
    lo = hi = t0
    while sign * f(lo) > 0:
        lo -= step
        step *= 2
    step = mp.mpf("0.01")
    while sign * f(hi) < 0:
        hi += step
        step *= 2
    # Safeguarded Newton in log x: f'(t) = +-x pdf(x) / tail(x), bisecting when a step leaves
    # the bracket; stops once a step is below 1E-52 (x then has 50 correct digits).
    def slope(t: object) -> object:
        x = mp.exp(t)
        value = tail(x)
        if not value > 0:
            return None
        log_pdf = (a - 1) * mp.log(x) - x - mp.loggamma(a) + mp.log(x)
        return sign * mp.exp(log_pdf - mp.log(value))

    t = (lo + hi) / 2
    for _ in range(200):
        value = f(t)
        if sign * value < 0:
            lo = t
        else:
            hi = t
        derivative = slope(t)
        candidate = t - value / derivative if derivative else (lo + hi) / 2
        if not lo < candidate < hi:
            candidate = (lo + hi) / 2
        if abs(candidate - t) < mp.mpf(10) ** -52 or hi - lo < mp.mpf(10) ** -52:
            t = candidate
            break
        t = candidate
    root = t
    return 2 * mp.exp(root)


def parse_show(path: str, sheet: str) -> dict[str, tuple[str, str, str]]:
    with open(path) as handle:
        text = handle.read()
    blocks = re.findall(
        rf"^{sheet}!(A\d+)\s+(\w+)\n\s+formula : (.*)\n\s+expected: (.*)\n\s+actual  : (.*)$", text, re.M
    )
    return {cell: (kind, expected, actual) for cell, kind, _, expected, actual in blocks}


def score(case_path: str, show_path: str) -> None:
    import mpmath as mp  # noqa: PLC0415

    with open(case_path) as handle:
        case = json.load(handle)
    sheet = case["sheets"][0]["name"]
    cells = case["sheets"][0]["cells"]
    strata = case.get("hypotheses", {})
    with open(case_path.replace(".case.json", ".oracle.json")) as handle:
        oracle = json.load(handle)["sheets"][sheet]
    shown = parse_show(show_path, sheet)
    table: Counter[tuple[str, str]] = Counter()
    for cell, formula in sorted(cells.items(), key=lambda kv: int(kv[0][1:])):
        function, p_text, df_text = re.match(r"=([A-Z.]+)\(([^,]+),([^)]+)\)", formula).groups()  # type: ignore[union-attr]
        if function == "CHIINV":
            function = "CHISQ.INV.RT"
        # `1-1E-10` is Excel's double subtraction, as Python's.
        p_double = 1.0 - float(p_text[2:]) if p_text.startswith("1-") else float(p_text)
        df = int(float(df_text))
        stratum = f"{function} {strata.get(sheet + '!' + cell, 'x/probe').split('/')[1]}"
        excel = oracle.get(cell, {})
        kind, _, actual = shown.get(cell, ("Exact", "", ""))
        excel_value = excel.get("v")
        engine_value = excel_value if kind == "Exact" else actual
        excel_15 = kind in ("Exact", "NumericUlp")
        engine_error = isinstance(engine_value, str) and engine_value.startswith("#")
        excel_error = excel.get("t") == "e"
        if (function == "CHISQ.INV" and df > 10**10) or (engine_error and excel_error):
            math = None
        else:
            started = time.monotonic()
            math = math_quantile(function, p_double, df)
            print(f"# {cell} {time.monotonic() - started:.1f} s", file=sys.stderr, flush=True)
        if engine_error or excel_error:
            if engine_error != excel_error:
                verdict = "error-vs-number"
            else:
                verdict = "both-error"
        else:
            rel = abs(mp.mpf(float(engine_value)) - math) / abs(math)
            within_math = rel <= mp.mpf("1e-9") or abs(mp.mpf(float(engine_value)) - math) <= mp.mpf("1e-300")
            excel_rel = abs(mp.mpf(float(excel_value)) - math) / abs(math)
            if excel_15 and within_math:
                verdict = "both"
            elif excel_15:
                verdict = "excel-15-only"
            elif within_math:
                verdict = "math-only"
            else:
                verdict = "outside"
            if verdict != "both":
                print(
                    f"{cell} {formula} {verdict} {kind} engine={engine_value} excel={excel_value} "
                    f"math={mp.nstr(math, 17)} rel(engine)={mp.nstr(rel, 3)} rel(excel)={mp.nstr(excel_rel, 3)}"
                )
        table[(stratum, verdict)] += 1
    print(flush=True)
    for stratum in sorted({s for s, _ in table}):
        row = {v: n for (s, v), n in table.items() if s == stratum}
        print(stratum, dict(sorted(row.items())))


if __name__ == "__main__":
    if sys.argv[1] == "generate":
        generate(sys.argv[2])
    else:
        score(sys.argv[2], sys.argv[3])
