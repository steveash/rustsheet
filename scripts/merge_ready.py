class MarkerError(ValueError):
    """A marker block that does not follow the `merge-train-ready v1` format."""


@dataclass(frozen=True)
class Marker:
    """The parsed `merge-train-ready v1` block: every field validated."""

    head: str
    prev: str | None
    task: str | None
    reviewers: Mapping[str, str]
    marked_by: str

    def render(self) -> str:
        verdicts = " ".join(f"{name}={self.reviewers.get(name, NOT_APPLICABLE)}" for name in REVIEWERS)
        lines = [
            MARKER_OPEN,
            f"head: {self.head}",
            f"prev: {self.prev or NONE}",
            f"task: {self.task or NONE}",
            f"reviewers: {verdicts}",
            f"marked-by: {self.marked_by}",
            MARKER_CLOSE,
        ]
        return "\n".join(lines)


def sha_field(value: str, what: str) -> str:
    if not gh_client.SHA.fullmatch(value):
        raise MarkerError(f"{what} is not a 40-hex sha")
    return value


def parse_reviewers(value: str) -> dict[str, str]:
    """`name=VERDICT` pairs, each name a known reviewer at most once, each verdict a known one."""
    verdicts: dict[str, str] = {}
    for pair in value.split():
        name, _, verdict = pair.partition("=")
        if name not in REVIEWERS or name in verdicts:
            raise MarkerError(f"unknown or repeated reviewer {name[:40]!r}")
        if verdict not in VERDICTS:
            raise MarkerError(f"unknown verdict for {name}")
        verdicts[name] = verdict
    return verdicts


def has_marker(body: str) -> bool:
    return MARKER_OPEN in body


def without_footer(body: str) -> str:
    """`body` with line endings normalized and at most one trailing FOOTER removed."""
    return body.replace("\r\n", "\n").removesuffix(FOOTER)


def parse_marker(body: str) -> Marker:
    """The marker block that ends comment `body` (FOOTER aside); MarkerError when it is malformed."""
    body = without_footer(body)
    lines = body[body.rfind(MARKER_OPEN) :].strip().splitlines()
    if not has_marker(body) or len(lines) != len(MARKER_KEYS) + 2 or lines[0] != MARKER_OPEN:
        raise MarkerError("no complete marker block at the end of the comment")
    if lines[-1] != MARKER_CLOSE:
        raise MarkerError("the marker block is not closed")
    fields: dict[str, str] = {}
    for key, line in zip(MARKER_KEYS, lines[1:-1], strict=True):
        name, sep, value = line.partition(": ")
        if name != key or not sep:
            raise MarkerError(f"expected `{key}:`")
        fields[key] = value.strip()
    prev, task = fields["prev"], fields["task"]
    if task != NONE and not TASK_ID.fullmatch(task):
        raise MarkerError("task is not T-XXXX or none")
    if not merge_lock.valid_id(fields["marked-by"]):
        raise MarkerError("marked-by is not a valid id")
    return Marker(
        head=sha_field(fields["head"], "head"),
        prev=None if prev == NONE else sha_field(prev, "prev"),
        task=None if task == NONE else task,
        reviewers=parse_reviewers(fields["reviewers"]),
        marked_by=fields["marked-by"],
    )


# Verdict records (SPEC-0027 section 2, "Verdict records (v2)"; decision 0178, T-3207): one PR comment
# per reviewer, the reviewer's report and then this block, which ends the comment.
RECORD_OPEN = "<!-- merge-train-verdict v1"
RECORD_KEYS = ("head", "reviewer", "verdict")
RECORD_VERDICTS = (APPROVE, "REQUEST_CHANGES")
# A record's body leaves room for the session's FOOTER within GitHub's comment limit.
RECORD_MAX = 65536 - len(FOOTER)
TRUNCATED = "\n\n[report truncated to fit GitHub's comment limit]"
# The rollout key (decision 0178) in the switch file, read from origin/main like `mode`.
SWITCH = "scripts/merge_train.toml"
WARN, REQUIRE = "warn", "require"


@dataclass(frozen=True)
class Record:
    """The parsed `merge-train-verdict v1` block: the head a reviewer read and its verdict."""

    head: str
    reviewer: str
    verdict: str

    def render(self) -> str:
        fields = (self.head, self.reviewer, self.verdict)
        return "\n".join(
            [RECORD_OPEN, *(f"{k}: {v}" for k, v in zip(RECORD_KEYS, fields, strict=True)), MARKER_CLOSE]
        )


def neutralised(report: str) -> str:
    """`report` unable to open or close an HTML comment: a space goes into each `<!--` and `-->`.
    Neither replacement can form the other sequence, so one pass of each is enough."""
    return report.replace("\r\n", "\n").replace("<!--", "<! --").replace("-->", "-- >")


def record_body(record: Record, report: str) -> str:
    """The record comment: the neutralised report, cut (never the block) to fit RECORD_MAX."""
    block = "\n\n" + record.render()
    text = neutralised(report).strip()
    if len(text) + len(block) > RECORD_MAX:
        text = text[: RECORD_MAX - len(block) - len(TRUNCATED)] + TRUNCATED
    return text + block


def parse_record(body: str) -> Record:
    """The record block that ends comment `body` (FOOTER aside); MarkerError when it is malformed
    or when the body holds any other record block."""
    body = without_footer(body)
    if body.count(RECORD_OPEN) != 1:
        raise MarkerError("not exactly one record block in the comment")
    lines = body[body.rfind(RECORD_OPEN) :].strip().splitlines()
    if len(lines) != len(RECORD_KEYS) + 2 or lines[0] != RECORD_OPEN or lines[-1] != MARKER_CLOSE:
        raise MarkerError("no complete record block at the end of the comment")
    fields: dict[str, str] = {}
    for key, line in zip(RECORD_KEYS, lines[1:-1], strict=True):
        name, sep, value = line.partition(": ")
        if name != key or not sep:
            raise MarkerError(f"expected `{key}:`")
        fields[key] = value.strip()
    if fields["reviewer"] not in REVIEWERS or fields["verdict"] not in RECORD_VERDICTS:
        raise MarkerError("unknown reviewer or verdict")
    return Record(sha_field(fields["head"], "head"), fields["reviewer"], fields["verdict"])


def recorded_verdicts(comments: Sequence[object], authors: Authors, head: str) -> dict[str, str]:
    """Each reviewer's verdict on `head` by its newest record (server `created_at`, then id). Only
    unedited, well-formed records by writers count: an edit cannot turn a REQUEST_CHANGES into an
    APPROVE (decision 0178), and a comment with no `created_at` counts as edited (fails closed)."""
    found: list[tuple[str, int, Record]] = []
    for comment in comments:
        body, created = text_of(comment, "body"), text_of(comment, "created_at")
        if RECORD_OPEN not in body or not created or created != text_of(comment, "updated_at"):
            continue
        with contextlib.suppress(MarkerError):
            record = parse_record(body)
            if record.head == head and authors.writer(comment):
                found.append((created, int_of(comment, "id"), record))
    return {record.reviewer: record.verdict for _, _, record in sorted(found, key=lambda f: f[:2])}


def record_gaps(recorded: Mapping[str, str], needed: Sequence[str], head: str) -> list[str]:
    """What the records for `head` lack: each applicable reviewer's newest record must APPROVE."""
    gaps = [f"no verdict record from {name} on {head}" for name in needed if name not in recorded]
    return gaps + [
        f"{name}'s newest verdict record on {head} is {recorded[name]}"
        for name in needed
        if recorded.get(name, APPROVE) != APPROVE
    ]


def records_mode(text: str | None) -> str:
    """The `verdict_records` mode a switch file's text sets: WARN when the file or the key is
    absent (the rollout default), REQUIRE when the file does not parse or the value is not a
    mode (fails closed)."""
    if text is None:
        return WARN
    try:
        value = tomllib.loads(text).get("verdict_records", WARN)
    except tomllib.TOMLDecodeError:
        return REQUIRE
    return value if value in (WARN, REQUIRE) else REQUIRE


def applicable_reviewers(paths: Iterable[str] | None) -> tuple[str, ...]:
    """The reviewers a diff of `paths` needs; every reviewer when the paths are unknown (None)."""
    if paths is None:
        return REVIEWERS
    touches = any(p == root or p.startswith(root + "/") for p in paths for root in EXCEL_FIDELITY_PATHS)
    return REVIEWERS if touches else ALWAYS_REVIEWERS


def missing_approvals(verdicts: Mapping[str, str], needed: Sequence[str]) -> list[str]:
    return [name for name in needed if verdicts.get(name) != APPROVE]


def task_of_branch(branch: str) -> str | None:
    match = TASK_BRANCH.fullmatch(branch)
    return match[1] if match else None


# GitHub objects are JSON; these read one field of one without trusting its shape.
def field_of(value: object, *keys: str) -> object:
    for key in keys:
        value = value.get(key) if isinstance(value, dict) else None
    return value


def text_of(value: object, *keys: str) -> str:
    found = field_of(value, *keys)
    return found if isinstance(found, str) else ""


def label_names(pull: object) -> list[str]:
    """The names of a PR's (or issue's) labels."""
    labels = field_of(pull, "labels")
    return [text_of(label, "name") for label in labels] if isinstance(labels, list) else []


def int_of(value: object, *keys: str) -> int:
    found = field_of(value, *keys)
    return found if isinstance(found, int) and not isinstance(found, bool) else 0


@dataclass
class Authors:
    """Who counts as a writer of the repository (module docstring), one lookup per login."""

    client: Client
    user_owned: bool
    cache: dict[str, bool] = field(default_factory=dict)

    def writer(self, item: object) -> bool:
        login, association = text_of(item, "user", "login"), text_of(item, "author_association")
        if not gh_client.LOGIN.fullmatch(login):
            return False
        if login not in self.cache:
            try:
                self.cache[login] = self.client.permission(login) in WRITE_PERMISSIONS
            except GhError as error:
                # Only the proxy's refusal falls back; any other failed read fails `verify`.
                if PERMISSION_REFUSED not in str(error):
                    raise
                self.cache[login] = self.user_owned and association in WRITE_ASSOCIATIONS
        return self.cache[login]


def ci_state(
    runs: Sequence[object],
    check_runs: Sequence[object],
    docs_only: bool | None,
    events: Sequence[str] = ("pull_request",),
) -> tuple[str, list[str]]:
    """GREEN, PENDING or RED for a PR head, with the jobs that are not green.

    `runs` are the head's workflow runs, `check_runs` its check runs, and `docs_only` whether the
    PR's diff is docs-only (`run_heavy=false`; None when it cannot be told, which counts as no).
    `events` are the run events that count: a PR head's `pull_request`, a train's `push` and
    `workflow_dispatch` (SPEC-0027 section 4, step 6).
    """
    ci = [
        r
        for r in runs
        if text_of(r, "path") == CI_WORKFLOW and text_of(r, "event") in events and int_of(r, "id") > 0
    ]
    if not ci:
        return PENDING, ["no ci.yml run yet"]
    run = max(ci, key=lambda r: int_of(r, "id"))
    if text_of(run, "status") != "completed":
        return PENDING, ["the ci.yml run is still running"]
    if text_of(run, "conclusion") != "success":
        return RED, [f"the ci.yml run concluded {text_of(run, 'conclusion') or 'nothing'}"]
    suite = field_of(run, "check_suite_id")
    latest: dict[str, object] = {}
    for check in check_runs:
        if field_of(check, "app", "id") != ACTIONS_APP_ID or field_of(check, "check_suite", "id") != suite:
            continue
        name = text_of(check, "name")
        if int_of(check, "id") > int_of(latest.get(name), "id"):
            latest[name] = check
    pending, red = [], []
    for name in (*REQUIRED_JOBS, *HEAVY_JOBS):
        check = latest.get(name)
        conclusion = text_of(check, "conclusion")
        if check is None:
            red.append(f"{name}: missing")
        elif text_of(check, "status") != "completed":
            pending.append(name)
        elif conclusion == "skipped" and name in HEAVY_JOBS and docs_only is True:
            continue
        elif conclusion != "success":
            red.append(f"{name}: {conclusion or 'no conclusion'}")
    if red:
        return RED, red
    return (PENDING, pending) if pending else (GREEN, [])


@dataclass(frozen=True)
class Failure:
    check: str
    reason: str
    action: str


@dataclass(frozen=True)
class Verdict:
    """V1-V6 for one PR: ready when nothing failed."""

    pr: int
    marker: Marker | None = None
    comment_id: int | None = None
    updated_at: str = ""
    failures: tuple[Failure, ...] = ()
    # Verdict-record gaps under `verdict_records = "warn"`: reported, never acted on.
    warnings: tuple[str, ...] = ()

    @property
    def ready(self) -> bool:
        return self.marker is not None and not self.failures


class Repo:
    """The git reads of `verify`, in a clone whose `origin` is the PR's repository."""

    def __init__(self, root: Path = ROOT) -> None:
        self.root = root

    def git(self, *args: str, check: bool = True) -> str:
        return git(*args, root=self.root, check=check).stdout

    def fetch_head(self, pr: int) -> str:
        """The sha `refs/pull/<pr>/head` has on origin, fetched (branch names can be re-pointed)."""
        ref = f"refs/merge-ready/pull/{pr}"
        self.git("fetch", "-q", "--no-tags", REMOTE, f"+refs/pull/{pr}/head:{ref}")
        return self.git("rev-parse", "--verify", f"{ref}^{{commit}}").strip()

    def fetch_base(self) -> None:
        self.git(
            "fetch", "-q", "--no-tags", REMOTE, f"+refs/heads/{BASE_BRANCH}:refs/merge-ready/{BASE_BRANCH}"
        )

    def changed_paths(self, base: str, head: str) -> list[str] | None:
        """The paths changed from the single merge base of `base` and `head` to `head`; None when
        there is not exactly one merge base (every reviewer then applies)."""
        bases = self.git("merge-base", "--all", base, head, check=False).split()
        if len(bases) != 1:
            return None
        out = self.git("diff", "-z", "--no-renames", "--name-only", bases[0], head, "--")
        return [p for p in out.split("\0") if p]

    def carry_problem(self, prev: str, head: str) -> str | None:
        """Why `head` is not a clean merge of `main` into `prev` (SPEC-0027 section 2,
        "Carry-over"), or None when it is: a merge commit whose first parent is `prev`, whose
        second parent is on `main`, and whose tree `git merge-tree --write-tree` reproduces."""
        parents = self.git("rev-list", "--parents", "-n", "1", head).split()[1:]
        if len(parents) != 2 or parents[0] != prev:
            return "the head is not a merge commit whose first parent is the marked head"
        main = f"refs/merge-ready/{BASE_BRANCH}"
        if git("merge-base", "--is-ancestor", parents[1], main, root=self.root, check=False).returncode:
            return f"the merged commit is not on {BASE_BRANCH}"
        merged = git("merge-tree", "--write-tree", *parents, root=self.root, check=False)
        tree = merged.stdout.split("\n", 1)[0].strip()
        if merged.returncode != 0 or tree != self.git("rev-parse", f"{head}^{{tree}}").strip():
            return "the merge is not clean: its tree differs from a plain merge of its parents"
        return None

    def task_file(self, head: str, task: str) -> str | None:
        """The text of task `task`'s file in `head`'s tree, or None when it has none."""
        names = self.git("ls-tree", "-r", "-z", "--name-only", head, "--", "docs/tasks").split("\0")
        found = [n for n in names if (m := tasks.TASK_FILE.search(n)) and m[1] == task]
        return self.git("show", f"{head}:{found[0]}") if len(found) == 1 else None

    def switch_text(self) -> str | None:
        """The switch file on the `main` that `fetch_base` fetched; None when it has none."""
        shown = git("show", f"refs/merge-ready/{BASE_BRANCH}:{SWITCH}", root=self.root, check=False)
        return shown.stdout if shown.returncode == 0 else None


def task_done(text: str | None) -> bool:
    """Whether a task file is `status: done` with an `## Outcome` section."""
    if text is None:
        return False
    try:
        meta = tasks.front_matter(text, Path("task"))
    except ValueError:
        return False
    return meta.get("status") == "done" and re.search(r"^## Outcome\s*$", text, re.M) is not None


def marker_comments(comments: Sequence[object], authors: Authors) -> list[object]:
    """The comments by writers that carry a marker, oldest first (by `updated_at`, then id)."""
    candidates = [c for c in comments if has_marker(text_of(c, "body")) and authors.writer(c)]
    return sorted(candidates, key=lambda c: (text_of(c, "updated_at"), int_of(c, "id")))


def newest_marker(comments: Sequence[object], authors: Authors) -> tuple[object, Marker | MarkerError] | None:
    """The newest marker comment by a writer, parsed; None if none."""
    candidates = marker_comments(comments, authors)
    if not candidates:
        return None
    newest = candidates[-1]
    try:
        return newest, parse_marker(text_of(newest, "body"))
    except MarkerError as error:
        return newest, error


def pr_state_failures(pull: object, marked_task: str | None, head: str, repo: Repo) -> list[Failure]:
    """V5: draft flag, base, head repository and the task file, all repository-controlled.
    `marked_task` is the marker's task."""
    failures = []
    if field_of(pull, "draft") is not False:
        failures.append(Failure("V5", "the PR is a draft", UNLABEL))
    if text_of(pull, "base", "ref") != BASE_BRANCH:
        failures.append(Failure("V5", f"the base is not {BASE_BRANCH}", UNLABEL))
    head_repo = text_of(pull, "head", "repo", "full_name")
    if not head_repo or head_repo != text_of(pull, "base", "repo", "full_name"):
        failures.append(Failure("V5", "the head is not in this repository", UNLABEL))
    task = task_of_branch(text_of(pull, "head", "ref"))
    if marked_task != task:
        failures.append(Failure("V5", f"the marker's task is not the branch's ({task or NONE})", UNLABEL))
    elif task is not None and not task_done(repo.task_file(head, task)):
        failures.append(Failure("V5", f"{task} is not status: done with an Outcome on the head", UNLABEL))
    return failures


def head_state(
    client: Client, pull: object, head: str, repo: Repo
) -> tuple[list[str] | None, str, list[str]]:
    """The PR's changed paths (None when unknown: every reviewer applies) and its head's CI state
    by the "green" rule, with the jobs that are not green. Fetches `main`.

    `run_heavy=false` is told by the same classifier CI runs, because the proxy refuses the
    job-log download where CI prints it (decision 0149)."""
    base_sha = text_of(pull, "base", "sha")
    repo.fetch_base()
    paths = repo.changed_paths(base_sha, head) if gh_client.SHA.fullmatch(base_sha) else None
    docs_only = None if paths is None else not ci_changes.classify_range(base_sha, head, cwd=repo.root)
    state, jobs = ci_state(client.workflow_runs(head_sha=head), client.check_runs(head), docs_only)
    return paths, state, jobs


def verify(client: Client, pr: int, repo: Repo) -> Verdict:
    """V1-V6 of SPEC-0027 section 2 on PR `pr`. Raises GhError or GitError when a read fails."""
    pull = client.pull(pr)
    if READY_LABEL not in label_names(pull):
        return Verdict(pr, failures=(Failure("label", f"no {READY_LABEL} label", IGNORE),))
    authors = Authors(client, text_of(pull, "base", "repo", "owner", "type") == "User")
    # V1: the newest marker by a writer; comments by anyone else have no effect.
    comments = client.comments(pr)
    found = newest_marker(comments, authors)
    if found is None:
        return Verdict(pr, failures=(Failure("V1", "no marker by a writer", IGNORE),))
    comment, marker = found
    comment_id, updated_at = int_of(comment, "id") or None, text_of(comment, "updated_at")
    if isinstance(marker, MarkerError):
        failure = Failure("V1", f"malformed marker: {marker}", UNLABEL)
        return Verdict(pr, None, comment_id, updated_at, (failure,))

    # V2: the marker names the current head, and origin's refs/pull/<n>/head agrees.
    head = text_of(pull, "head", "sha")
    if marker.head != head or repo.fetch_head(pr) != head:
        failure = Failure("V2", f"readiness invalidated by a push (now {head[:40] or 'unknown'})", UNLABEL)
        return Verdict(pr, marker, comment_id, updated_at, (failure,))

    failures = pr_state_failures(pull, marker.task, head, repo)
    # V4: every applicable reviewer approved, by the marker and by the verdict records.
    paths, state, jobs = head_state(client, pull, head, repo)
    needed = applicable_reviewers(paths)
    missing = missing_approvals(marker.reviewers, needed)
    if missing:
        failures.append(Failure("V4", f"no APPROVE from {', '.join(missing)}", UNLABEL))
    gaps = record_check(comments, authors, repo, marker, needed)
    warnings: tuple[str, ...] = ()
    if gaps and records_mode(repo.switch_text()) == REQUIRE:
        failures.append(Failure("V4", "; ".join(gaps), UNLABEL))
    else:
        warnings = tuple(gaps)

    # V3: CI on the head by the "green" rule.
    if state == RED:
        failures.append(Failure("V3", f"CI red on {head}: {'; '.join(jobs)}", UNLABEL))
    elif state == PENDING:
        failures.append(Failure("V3", f"CI pending on {head}: {'; '.join(jobs)}", KEEP))

    # V6: no CHANGES_REQUESTED from a writer since the marker; anyone else's reviews have no effect.
    if any(
        text_of(review, "state") == "CHANGES_REQUESTED"
        and text_of(review, "submitted_at") > updated_at
        and authors.writer(review)
        for review in client.reviews(pr)
    ):
        failures.append(Failure("V6", "changes were requested after the marker", UNLABEL))
    return Verdict(pr, marker, comment_id, updated_at, tuple(failures), warnings)


def record_check(
    comments: Sequence[object], authors: Authors, repo: Repo, marker: Marker, needed: Sequence[str]
) -> list[str]:
    """V4's record lookup (decision 0178): the gaps in the records for the marker's head, or for
    its `prev` when it carries verdicts over, whose carry check is then re-run. Needs `main`
    fetched (`head_state`)."""
    if marker.prev is None:
        return record_gaps(recorded_verdicts(comments, authors, marker.head), needed, marker.head)
    problem = repo.carry_problem(marker.prev, marker.head)
    if problem:
        return [f"the carry-over from {marker.prev} does not hold: {problem}"]
    return record_gaps(recorded_verdicts(comments, authors, marker.prev), needed, marker.prev)


# `mark` (SPEC-0027 section 2, T-3040, decision 0161).
LABEL_STYLES = {
    READY_LABEL: ("0e8a16", "Marked ready for the merge train (make mark-ready, SPEC-0027)"),
    EJECTED_LABEL: ("d93f0b", "Ejected from a merge train; mark again after fixing (SPEC-0027)"),
    STOP_LABEL: ("b60205", "Stops the merge train while any open PR carries it (SPEC-0027)"),
}
# The step-mode actions `mark` prints (SPEC-0027 section 4, "GitHub access"); scripts/merge_step.py
# holds the whole schema, the merger's actions included, and validates these (decision 0169).
STEP_LABEL, STEP_UNLABEL, STEP_COMMENT = "label", "unlabel", "comment"


class Refusal(Exception):
    """`mark` refuses: the PR is not one to mark now (exit 1, with the reason)."""


@dataclass(frozen=True)
class Plan:
    """What `mark` writes: the marker comment (None when this head already has one), whether
    the PR still needs the label, and whether it still carries `merge-train-ejected`, which
    marking again removes (SPEC-0027 section 6, "After an ejection")."""

    pr: int
    marker: Marker
    body: str | None
    label: bool
    unlabel: bool
    labels: tuple[str, ...]
    # The reviewers whose verdict stood in for a missing record (`verdict_records = "warn"`).
    warnings: tuple[str, ...] = ()

    def actions(self) -> list[dict[str, object]]:
        """The writes as step-mode actions, in order: the comment first, so a labelled PR always
        has its marker. `labels` is the PR's whole label set once marked (`ready-to-merge` in,
        `merge-train-ejected` out), the same in both label actions, for a tool that replaces the
        set instead of adding or removing one label."""
        out: list[dict[str, object]] = []
        if self.body is not None:
            out.append({"action": STEP_COMMENT, "pr": self.pr, "body": self.body})
        if self.label:
            out.append(
                {"action": STEP_LABEL, "pr": self.pr, "label": READY_LABEL, "labels": list(self.labels)}
            )
        if self.unlabel:
            out.append(
                {"action": STEP_UNLABEL, "pr": self.pr, "label": EJECTED_LABEL, "labels": list(self.labels)}
            )
        return out


def marker_body(marker: Marker) -> str:
    """The whole marking comment: one constant sentence, then the block."""
    return (
        f"Marked ready for the merge train at `{marker.head}` "
        "(`make mark-ready`, SPEC-0027 section 2).\n\n" + marker.render()
    )


def writer_markers(comments: Sequence[object], authors: Authors) -> list[Marker]:
    """The well-formed markers by writers, oldest first. A malformed one is skipped: it holds no
    head or verdicts to match or carry, and `verify` already unlabels a PR whose newest is one."""
    found = []
    for comment in marker_comments(comments, authors):
        with contextlib.suppress(MarkerError):
            found.append(parse_marker(text_of(comment, "body")))
    return found


def checked_out_head(client: Client, pr: int, repo: Repo) -> tuple[object, str]:
    """The PR and its head sha, which the local HEAD and origin's refs/pull/<pr>/head must equal."""
    pull = client.pull(pr)
    head = text_of(pull, "head", "sha")
    local = repo.git("rev-parse", "--verify", "HEAD^{commit}").strip()
    if not gh_client.SHA.fullmatch(head) or local != head or repo.fetch_head(pr) != head:
        raise Refusal(f"the local HEAD, refs/pull/{pr}/head and the PR's head.sha differ")
    return pull, head


def plan_record(client: Client, pr: int, repo: Repo, reviewer: str, verdict: str, report: str) -> str:
    """The body of `reviewer`'s verdict record on the local HEAD (`make verdict-record`, decision
    0178); Refusal when HEAD is not the PR head or the report is empty."""
    if reviewer not in REVIEWERS or verdict not in RECORD_VERDICTS:
        raise Refusal(f"REVIEWER is one of {', '.join(REVIEWERS)}; VERDICT one of {', '.join(RECORD_VERDICTS)}")
    if not report.strip():
        raise Refusal("the report is empty: a record carries the reviewer's report")
    _, head = checked_out_head(client, pr, repo)
    return record_body(Record(head, reviewer, verdict), report)


def plan_mark(client: Client, pr: int, repo: Repo, review: str | None, carry: bool, by: str) -> Plan:
    """The refusals of SPEC-0027 section 2 on PR `pr`, then what to write. Reads only; raises
    Refusal, or GhError or GitError when a read fails.

    The verdicts come from the verdict records (decision 0178) for the head, or for `prev` with
    `carry`. While `verdict_records = "warn"`, a reviewer with no record takes its verdict from
    `review` or the carried marker, with a warning; in `require` that is a refusal."""
    if not merge_lock.valid_id(by):
        raise Refusal("no valid marker id: pass --by or set CLAUDE_CODE_SESSION_ID")
    if carry and review is not None:
        raise Refusal("give the verdicts (REVIEW) or --carry, which takes the previous marker's, not both")
    pull, head = checked_out_head(client, pr, repo)
    authors = Authors(client, text_of(pull, "base", "repo", "owner", "type") == "User")
    comments = client.comments(pr)
    markers = writer_markers(comments, authors)
    already = next((m for m in markers if m.head == head), None)
    prev, fallback, source = None, None, "REVIEW"
    if carry and already is not None:
        # A re-run after a partial write: the head's own marker carries the verdicts.
        prev, fallback, source = already.prev, dict(already.reviewers), "the carried marker"
    elif carry:
        older = [m for m in markers if m.head != head]
        if not older:
            raise Refusal("--carry needs an earlier marker by a writer on this PR")
        prev, fallback, source = older[-1].head, dict(older[-1].reviewers), "the carried marker"
        repo.fetch_base()
        problem = repo.carry_problem(prev, head)
        if problem:
            raise Refusal(f"--carry refused: {problem}; run the reviewers again")
    elif review is not None:
        try:
            fallback = parse_reviewers(review)
        except MarkerError as error:
            raise Refusal(f"REVIEW: {error}") from error

    # V5's own checks: draft, base, fork and the task file (none for a branch without a task id:
    # task-only and steward PRs, SPEC-0027 section 2).
    task = task_of_branch(text_of(pull, "head", "ref"))
    failures = pr_state_failures(pull, already.task if already else task, head, repo)
    if failures:
        raise Refusal("; ".join(f.reason for f in failures))
    paths, state, jobs = head_state(client, pull, head, repo)
    needed = applicable_reviewers(paths)
    reviewed = prev or head
    recorded = recorded_verdicts(comments, authors, reviewed)
    unrecorded = [name for name in needed if name not in recorded]
    if unrecorded and (fallback is None or records_mode(repo.switch_text()) == REQUIRE):
        raise Refusal(
            f"no verdict record on {reviewed} from {', '.join(unrecorded)}: post each with make verdict-record "
            "(REVIEW or CARRY stands in for a missing one only while verdict_records = warn)"
        )
    verdicts = {**(fallback or {}), **recorded}
    missing = missing_approvals(verdicts, needed)
    if missing:
        raise Refusal(f"no APPROVE from {', '.join(missing)}")
    if state != GREEN:
        raise Refusal(f"CI is {state} on {head}: {'; '.join(jobs)}")

    marker = already or Marker(head, prev, task, verdicts, by)
    # Every name goes back into a step-mode action, so each must be a label name gh_client accepts.
    labels = [gh_client.checked(gh_client.LABEL, name, "label") for name in label_names(pull)]
    return Plan(
        pr,
        marker,
        None if already else marker_body(marker),
        READY_LABEL not in labels,
        EJECTED_LABEL in labels,
        tuple(dict.fromkeys([*(name for name in labels if name != EJECTED_LABEL), READY_LABEL])),
        tuple(f"no verdict record from {name} on {reviewed}: its verdict comes from {source}" for name in unrecorded),
    )


def missing_labels(client: Client) -> list[str]:
    """The merge-train labels the repository does not have."""
    return [name for name in LABELS if client.label(name) is None]


def create_labels(client: Client, names: Iterable[str]) -> None:
    """Creates the merge-train labels `names` with their colour and description."""
    for name in names:
        color, description = LABEL_STYLES[name]
        client.create_label(name, color, description)


def apply(client: Client, plan: Plan) -> None:
    """Performs the plan's writes through the client (CI, or a session allowed to write), in
    `Plan.actions`' order. A push in between is caught by the caller's `verify` (V2)."""
    create_labels(client, missing_labels(client))
    if plan.body is not None:
        client.comment(plan.pr, plan.body)
    if plan.label:
        client.add_label(plan.pr, READY_LABEL)
    if plan.unlabel:
        client.remove_label(plan.pr, EJECTED_LABEL)


def report(verdict: Verdict) -> str:
    if verdict.ready and verdict.marker is not None:
        lines = [f"#{verdict.pr} ready: head {verdict.marker.head}, marker comment {verdict.comment_id} ({verdict.updated_at})"]
    else:
        lines = [f"#{verdict.pr} not ready:"]
        lines += [f"  {f.check} ({f.action}): {f.reason}" for f in verdict.failures]
    lines += [f"  warning (verdict_records = warn): {w}" for w in verdict.warnings]
    return "\n".join(lines)


def main(argv: list[str], root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("verify", help="run V1-V6 on a PR (reads only)")
    check.add_argument("--pr", required=True)
    mark = sub.add_parser("mark", help="mark a green, approved PR ready (the marker and the label)")
    mark.add_argument("--pr", required=True)
    mark.add_argument("--review", help='"security=APPROVE architecture=APPROVE quality=APPROVE ..."')
    mark.add_argument("--carry", action="store_true", help="carry the verdicts over a clean merge of main")
    mark.add_argument("--by", default=os.environ.get("CLAUDE_CODE_SESSION_ID", ""), help="the marker id")
    mark.add_argument("--step", action="store_true", help="print the writes as step-mode actions")
    record = sub.add_parser("record", help="post a reviewer's verdict record for the local HEAD")
    record.add_argument("--pr", required=True)
    record.add_argument("--reviewer", required=True, help=" | ".join(REVIEWERS))
    record.add_argument("--verdict", required=True, help=" | ".join(RECORD_VERDICTS))
    record.add_argument("--report", required=True, type=Path, help="the file holding the reviewer's report")
    record.add_argument("--step", action="store_true", help="print the write as a step-mode action")
    labels = sub.add_parser("labels", help="list the missing merge-train labels; --create creates them")
    labels.add_argument("--create", action="store_true")
    args = parser.parse_args(argv)
    client = gh_client.from_remote(root, REMOTE)
    if client is None:
        print("merge_ready: origin is not a github.com repository", file=sys.stderr)
        return 2
    try:
        if args.command == "labels":
            missing = missing_labels(client)
            if args.create:
                create_labels(client, missing)
            print(f"{'created' if args.create else 'missing'}: {', '.join(missing) or 'none'}")
            return 1 if missing and not args.create else 0
        pr = gh_client.number(args.pr)
        if args.command == "mark":
            return run_mark(client, pr, Repo(root), args)
        if args.command == "record":
            return run_record(client, pr, Repo(root), args)
        verdict = verify(client, pr, Repo(root))
    except (GhError, GitError) as error:
        print(f"merge_ready: {error}", file=sys.stderr)
        return 2
    print(report(verdict))
    return 0 if verdict.ready else 1


def run_record(client: Client, pr: int, repo: Repo, args: argparse.Namespace) -> int:
    """`record`: 1 on a refusal; otherwise the comment posted (or, with --step, printed), and 0."""
    try:
        report = args.report.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        print(f"merge_ready: cannot read the report: {error}", file=sys.stderr)
        return 2
    try:
        body = plan_record(client, pr, repo, args.reviewer, args.verdict, report)
    except Refusal as refusal:
        print(f"merge_ready: no verdict record for #{pr}: {refusal}", file=sys.stderr)
        return 1
    action = {"action": STEP_COMMENT, "pr": pr, "body": body}
    if args.step:
        import merge_step  # here: merge_step imports this module

        merge_step.validate(action)
        print(json.dumps(action, sort_keys=True))
        print("merge_ready: post this comment exactly as printed", file=sys.stderr)
        return 0
    posted = client.comment(pr, body)
    print(f"#{pr}: {args.reviewer} {args.verdict} recorded (comment {int_of(posted, 'id')})")
    return 0


def run_mark(client: Client, pr: int, repo: Repo, args: argparse.Namespace) -> int:
    """`mark`: 1 on a refusal; otherwise the writes (or, with --step, the actions to perform and
    then `verify` to run), and 0. With direct writes, `verify` reads the result back, and a PR
    still not ready after them (a push in between, or a write that did not land) exits 2."""
    try:
        plan = plan_mark(client, pr, repo, args.review, args.carry, args.by)
    except Refusal as refusal:
        print(f"merge_ready: not marking #{pr}: {refusal}", file=sys.stderr)
        return 1
    for warning in plan.warnings:
        print(f"merge_ready: warning: {warning}", file=sys.stderr)
    if not plan.actions():
        print(f"#{pr} is already marked at {plan.marker.head}")
        return 0
    if args.step:
        import merge_step  # here: merge_step imports this module

        for action in plan.actions():
            merge_step.validate(action)  # the merger's schema (decision 0169)
            print(json.dumps(action, sort_keys=True))
        print(
            f"merge_ready: perform these actions in order, then run make merge-ready-verify PR={pr}",
            file=sys.stderr,
        )
        return 0
    apply(client, plan)
    verdict = verify(client, pr, repo)
    print(report(verdict))
    return 0 if verdict.ready else 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
