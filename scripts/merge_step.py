#!/usr/bin/env python3
"""The merge train's step mode (SPEC-0027 section 4, "GitHub access"; T-3077, decision 0169).

  scripts/merge_step.py ack --seq N [--refused]   # the session performed (or saw refused) action N

A routine session cannot write through `gh api` (T-3001's probe), so a `--step` run of the merger
writes through `StepClient`: it reads through the real client, and each write becomes one JSON
action from a closed enum that the script fills in full. The script prints the action and waits,
still holding the lock; the session performs exactly that action with the GitHub MCP tools and
runs `ack`; the script then reads GitHub back. A difference from the expected result, no ack, or
an ack for another action aborts the run (`StepError`): nothing is skipped or reordered.
`merge_ready.py mark --step` prints actions of the same schema (`validate`).
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import TypeVar

import gh_client
import merge_ready
from gh_client import Client, GhError, Request
from merge_lock import GitError, git

ROOT = Path(__file__).resolve().parent.parent

# `merge_ready.py mark --step` prints the first two.
COMMENT, LABEL = merge_ready.STEP_COMMENT, merge_ready.STEP_LABEL
UNLABEL, MERGE = "unlabel", "merge"
CREATE_PULL, DELETE_BRANCH, DISPATCH = "create_pull", "delete_branch", "dispatch"
# Each action's fields besides `action` and the optional `seq` (the closed enum of the spec).
FIELDS: Mapping[str, frozenset[str]] = {
    COMMENT: frozenset({"pr", "body"}),
    LABEL: frozenset({"pr", "label", "labels"}),
    UNLABEL: frozenset({"pr", "label", "labels"}),
    MERGE: frozenset({"pr", "expectedHeadSha", "title", "message", "method"}),
    CREATE_PULL: frozenset({"title", "head", "base", "body"}),
    DELETE_BRANCH: frozenset({"branch"}),
    DISPATCH: frozenset({"workflow", "ref"}),
}
BODY_MAX = 65536  # GitHub's limit on comment and PR bodies, as gh_client enforces it
TITLE_MAX = 256
# What the session's GitHub write path appends to every comment it posts (T-3164); a body read
# back counts with or without exactly this suffix.
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

ACK_TIMEOUT = 10 * 60
ACK_POLL = 2
READBACK_TRIES = 5  # GitHub's lists can lag a write by a few seconds
READBACK_POLL = 3
DONE, REFUSED = "done", "refused"
STEP_DIR = "merge-train-step"  # under the git directory: never committed, one per clone
State = TypeVar("State")


class StepError(Exception):
    """The step mode aborts: an action not performed, not acked, or read back different."""


def fail(what: str) -> StepError:
    return StepError(f"invalid step action: {what}")


def text_field(action: Mapping[str, object], key: str, limit: int, *, one_line: bool = False) -> str:
    value = action.get(key)
    if not isinstance(value, str) or not value or len(value) > limit or (one_line and "\n" in value):
        raise fail(f"{key} is not a non-empty {'single-line ' if one_line else ''}text of at most {limit}")
    return value


def validate(action: Mapping[str, object]) -> None:
    """StepError unless `action` follows the schema exactly: a known action, exactly its fields,
    and each value within the bounds gh_client puts on the same direct write."""
    kind = action.get("action")
    if not isinstance(kind, str) or kind not in FIELDS:
        raise fail(f"unknown action {str(kind)[:40]!r}")
    keys = set(action) - {"action", "seq"}
    if keys != FIELDS[kind]:
        raise fail(f"{kind} has fields {sorted(keys)}, not {sorted(FIELDS[kind])}")
    seq = action.get("seq", 1)
    if not isinstance(seq, int) or isinstance(seq, bool) or seq < 1:
        raise fail("seq is not a positive integer")
    try:
        if "pr" in keys:
            pr = action["pr"]
            if not isinstance(pr, int) or isinstance(pr, bool):
                raise fail("pr is not an integer")
            gh_client.number(pr)
        if kind in (LABEL, UNLABEL):
            label, labels = action["label"], action["labels"]
            if label not in merge_ready.LABELS:
                raise fail(f"label {str(label)[:40]!r} is not a merge-train label")
            if not isinstance(labels, list) or len(set(map(str, labels))) != len(labels):
                raise fail("labels is not a list of distinct names")
            for name in labels:
                gh_client.checked(gh_client.LABEL, str(name), "label")
            if (label in labels) != (kind == LABEL):
                raise fail(f"labels does not show the {kind} of {label}")
        if kind in (COMMENT, CREATE_PULL):
            text_field(action, "body", BODY_MAX)
        if kind in (MERGE, CREATE_PULL):
            text_field(action, "title", TITLE_MAX, one_line=True)
        if kind == MERGE:
            gh_client.checked(gh_client.SHA, str(action["expectedHeadSha"]), "expectedHeadSha")
            if not isinstance(action["message"], str) or len(action["message"]) > BODY_MAX:
                raise fail("message is not a text")
            if action["method"] != "squash":
                raise fail("method is not squash")
        if kind == CREATE_PULL:
            gh_client.branch_name(str(action["head"]))
            gh_client.branch_name(str(action["base"]))
        if kind == DELETE_BRANCH and gh_client.branch_name(str(action["branch"])) == merge_ready.BASE_BRANCH:
            raise fail("the base branch is never deleted")
        if kind == DISPATCH:
            gh_client.checked(gh_client.WORKFLOW, str(action["workflow"]), "workflow")
            gh_client.branch_name(str(action["ref"]))
    except GhError as error:
        raise fail(str(error)) from error


def same_body(found: str, body: str) -> bool:
    """`found` is `body`, alone or followed by exactly the session's footer (line endings aside)."""
    found = found.replace("\r\n", "\n")
    return found in (body, body + FOOTER)


def read_only(request: Request) -> Request:
    """`request` when it only reads: every write of a step run is an action."""
    if request.method != "GET":
        raise StepError(f"step mode: {request.method} {request.path} is not a step action")
    return request


# The session: performs an action and says whether it was DONE or REFUSED; raises StepError otherwise.
Session = Callable[[dict[str, object]], str]


class StepClient(Client):
    """A client for a `--step` run: reads go through `inner`; each write is one action that
    `session` performs, between a read of the state it changes and the read-back of that state.
    `sleep` is injectable so tests read back at once."""

    def __init__(self, inner: Client, session: Session, sleep: Callable[[float], None] = time.sleep) -> None:
        self.base = inner.base
        self.inner, self.session, self.sleep = inner, session, sleep
        self.seq = 0

    def send(self, request: Request) -> object:
        return self.inner.send(read_only(request))

    def send_cursor(self, request: Request) -> tuple[object, str | None]:
        return self.inner.send_cursor(read_only(request))

    def step(
        self, action: dict[str, object], observe: Callable[[], State], expected: Callable[[State], State]
    ) -> None:
        """Performs `action` through the session. `observe` reads the state it changes, and
        `expected(before)` is that state once the action is done."""
        self.seq += 1
        action = {"action": action.pop("action"), "seq": self.seq, **action}
        validate(action)
        before = observe()
        want = expected(before)
        answer = self.session(action)
        if answer not in (DONE, REFUSED):
            raise StepError(f"step {self.seq}: unknown answer {answer!r}")
        target = want if answer == DONE else before
        after = observe()
        for _ in range(READBACK_TRIES - 1):
            if after == target:
                break
            self.sleep(READBACK_POLL)
            after = observe()
        if after != target:
            raise StepError(
                f"step {self.seq} ({action['action']}): GitHub reads {after!r} after the session "
                f"answered {answer}, expected {target!r}"
            )
        if answer == REFUSED:
            raise GhError(f"step {self.seq} ({action['action']}): the session reports the write refused")

    # The state each write changes.
    def labels(self, pr: int) -> frozenset[str]:
        return frozenset(merge_ready.label_names(self.pull(pr)))

    def comments_like(self, pr: int, body: str) -> list[object]:
        """The writers' comments on `pr` whose body is `body` (V1's session rule: author_association)."""
        return [
            c
            for c in self.comments(pr)
            if merge_ready.text_of(c, "author_association") in merge_ready.WRITE_ASSOCIATIONS
            and same_body(merge_ready.text_of(c, "body"), body)
        ]

    def pulls_like(self, title: str, head: str, body: str, base: str) -> list[object]:
        return [
            p
            for p in self.pulls()
            if merge_ready.text_of(p, "head", "ref") == head
            and merge_ready.text_of(p, "base", "ref") == base
            and merge_ready.text_of(p, "title") == title
            and same_body(merge_ready.text_of(p, "body"), body)
        ]

    def branch_exists(self, name: str) -> bool:
        try:
            self.call("GET", f"git/ref/heads/{gh_client.branch_name(name)}")
        except GhError as error:
            if gh_client.NOT_FOUND in str(error):
                return False
            raise
        return True

    def merge_state(self, pr: int) -> tuple[bool, str, str]:
        """(merged, head sha, the squash commit's message when merged)."""
        pull = self.pull(pr)
        merged = merge_ready.field_of(pull, "merged") is True
        sha = merge_ready.text_of(pull, "merge_commit_sha")
        message = merge_ready.text_of(self.commit(sha), "message").strip() if merged and sha else ""
        return merged, merge_ready.text_of(pull, "head", "sha"), message

    def dispatched(self, workflow: str, ref: str) -> int:
        return sum(
            1
            for r in self.workflow_runs(branch=ref, event="workflow_dispatch")
            if merge_ready.text_of(r, "path").endswith(f"/{workflow}")
        )

    # The writes.
    def comment(self, pr: int | str, body: str) -> dict[str, object]:
        n = gh_client.number(pr)
        self.step(
            {"action": COMMENT, "pr": n, "body": body},
            lambda: len(self.comments_like(n, body)),
            lambda count: count + 1,
        )
        return gh_client.as_dict(self.comments_like(n, body)[-1])

    def add_label(self, pr: int | str, label: str) -> object:
        return self.relabel(gh_client.number(pr), label, add=True)

    def remove_label(self, pr: int | str, label: str) -> object:
        return self.relabel(gh_client.number(pr), label, add=False)

    def relabel(self, pr: int, label: str, *, add: bool) -> object:
        before = self.labels(pr)
        after = before | {label} if add else before - {label}
        self.step(
            {"action": LABEL if add else UNLABEL, "pr": pr, "label": label, "labels": sorted(after)},
            lambda: self.labels(pr),
            lambda _: after,
        )
        return {}

    def merge(
        self, pr: int | str, head_sha: str, *, title: str, message: str = "", method: str = "squash"
    ) -> dict[str, object]:
        n = gh_client.number(pr)
        text = f"{title}\n\n{message}".strip() if message else title
        self.step(
            {
                "action": MERGE,
                "pr": n,
                "expectedHeadSha": head_sha,
                "title": title,
                "message": message,
                "method": method,
            },
            lambda: self.merge_state(n),
            lambda _: (True, head_sha, text),
        )
        return {"sha": merge_ready.text_of(self.pull(n), "merge_commit_sha"), "merged": True}

    def create_pull(self, title: str, head: str, body: str, base: str = "main") -> dict[str, object]:
        self.step(
            {"action": CREATE_PULL, "title": title, "head": head, "base": base, "body": body},
            lambda: len(self.pulls_like(title, head, body, base)),
            lambda count: count + 1,
        )
        return gh_client.as_dict(self.pulls_like(title, head, body, base)[-1])

    def delete_branch(self, name: str) -> object:
        self.step(
            {"action": DELETE_BRANCH, "branch": name}, lambda: self.branch_exists(name), lambda _: False
        )
        return None

    def dispatch(self, workflow: str, ref: str, inputs: Mapping[str, str] | None = None) -> object:
        if inputs:
            raise StepError("step mode: a dispatch with inputs is not a step action")
        self.step(
            {"action": DISPATCH, "workflow": workflow, "ref": ref},
            lambda: self.dispatched(workflow, ref),
            lambda count: count + 1,
        )
        return {}

    def create_label(self, label: str, color: str, description: str) -> dict[str, object]:
        raise StepError("step mode: creating a label is not a step action (make merge-labels)")


def step_dir(root: Path) -> Path:
    return Path(git("rev-parse", "--absolute-git-dir", root=root).stdout.strip()) / STEP_DIR


class AckFile:
    """The session of a `--step` run: prints the action as one JSON line, records it as pending,
    and waits for `ack` to answer for its sequence number."""

    def __init__(
        self,
        root: Path,
        clock: Callable[[], float] = time.monotonic,
        sleep: Callable[[float], None] = time.sleep,
        timeout: float = ACK_TIMEOUT,
    ) -> None:
        self.dir = step_dir(root)
        self.clock, self.sleep, self.timeout = clock, sleep, timeout

    def __call__(self, action: dict[str, object]) -> str:
        self.dir.mkdir(exist_ok=True)
        (self.dir / "ack").unlink(missing_ok=True)
        (self.dir / "pending").write_text(json.dumps(action, sort_keys=True))
        print(json.dumps(action, sort_keys=True), flush=True)
        print(
            f"merge_train: perform this action, then run make merge-train-ack SEQ={action['seq']}"
            " (REFUSED=1 if GitHub refused it)",
            file=sys.stderr,
            flush=True,
        )
        deadline = self.clock() + self.timeout
        try:
            while self.clock() < deadline:
                ack = self.dir / "ack"
                if ack.exists():
                    seq, _, answer = ack.read_text().strip().partition(" ")
                    if seq != str(action["seq"]) or answer not in (DONE, REFUSED):
                        raise StepError(
                            f"step {action['seq']}: the ack is for {ack.read_text().strip()[:40]!r}"
                        )
                    return answer
                self.sleep(ACK_POLL)
            raise StepError(
                f"step {action['seq']} ({action['action']}) was not acked within {self.timeout // 60:.0f} min"
            )
        finally:
            for name in ("pending", "ack"):
                (self.dir / name).unlink(missing_ok=True)


def ack(root: Path, seq: int, refused: bool) -> int:
    """Answers the pending action `seq`: 1 when no action or another one is pending."""
    folder = step_dir(root)
    try:
        pending = json.loads((folder / "pending").read_text())
    except (OSError, ValueError):
        print("merge_step: no step action is pending", file=sys.stderr)
        return 1
    if not isinstance(pending, dict) or pending.get("seq") != seq:
        print(
            f"merge_step: the pending action is not {seq}: {json.dumps(pending, sort_keys=True)[:200]}",
            file=sys.stderr,
        )
        return 1
    (folder / "ack").write_text(f"{seq} {REFUSED if refused else DONE}")
    return 0


def main(argv: list[str], root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(prog="merge_step.py")
    sub = parser.add_subparsers(dest="command", required=True)
    acked = sub.add_parser("ack", help="the session performed (or saw refused) the pending action")
    acked.add_argument("--seq", type=int, required=True)
    acked.add_argument("--refused", action="store_true")
    args = parser.parse_args(argv)
    try:
        return ack(root, args.seq, args.refused)
    except GitError as error:
        print(f"merge_step: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
