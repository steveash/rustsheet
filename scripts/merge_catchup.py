#!/usr/bin/env python3
"""Catch up a PR the merge train ejected for a conflict with main, when the conflict is only in
the known-failure lists (decision 0205).

  scripts/merge_catchup.py --pr N   # exit 0: pushed; 1: refused (left unchanged); 2: error

In this checkout, which must have no local changes, it does the following:
- checks out the PR's branch and merges `origin/main` into it;
- if any conflicted path lies outside `eval/baseline/`, aborts and refuses: that conflict needs
  the PR's author;
- otherwise takes `main`'s side of each conflicted baseline and runs `make eval-baseline`, which
  re-records the lists and refuses regressions (decision 0093), then commits;
- pushes the result to the PR branch (never forced);
- returns to the checkout's original HEAD.

When CI is green on the pushed head, `make mark-ready PR=N CARRY=1` re-marks the PR: the
carry-over rule accepts a merge of main whose only resolution is in `eval/baseline/`, because the
eval gate checks those files against the engine (merge_ready.Repo.carry_problem).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

import gh_client
import merge_ready
from merge_lock import GitError, git

ROOT = Path(__file__).resolve().parent.parent
REMOTE = "origin"
RERECORD = ("make", "-s", "eval-baseline")
COMMIT_TRAILER = "Generated by `make catch-up` (decision 0205)."


class Refused(Exception):
    """The PR cannot be caught up here; nothing was pushed."""


def baseline_only(paths: Sequence[str]) -> bool:
    """Whether every one of the conflicted `paths` is a known-failure list (and there is one)."""
    return bool(paths) and all(p.startswith(merge_ready.BASELINE_DIR) for p in paths)


def rerecord(root: Path) -> int:
    """`make eval-baseline` in `root`: re-records eval/baseline/ and refuses regressions."""
    return subprocess.run(RERECORD, cwd=root, stdin=subprocess.DEVNULL, check=False).returncode


def catch_up(root: Path, branch: str, record: Callable[[Path], int] = rerecord) -> str:
    """Merges `origin/main` into `branch` as the module docstring says and pushes it; returns the
    pushed head. Raises Refused when it cannot (nothing pushed); the checkout's HEAD is restored."""
    branch = gh_client.branch_name(branch)
    if git("status", "--porcelain", "--untracked-files=no", root=root).stdout.strip():
        raise Refused("the checkout has local changes")
    start = git("rev-parse", "HEAD", root=root).stdout.strip()
    git("fetch", "-q", REMOTE, merge_ready.BASE_BRANCH, branch, root=root)
    try:
        git("checkout", "-q", "--detach", f"{REMOTE}/{branch}", root=root)
        before = git("rev-parse", "HEAD", root=root).stdout.strip()
        merged = git(
            "merge", "-q", "--no-edit", f"{REMOTE}/{merge_ready.BASE_BRANCH}", root=root, check=False
        )
        if merged.returncode != 0:
            conflicted = git("diff", "--name-only", "--diff-filter=U", root=root).stdout.split()
            if not baseline_only(conflicted):
                git("merge", "--abort", root=root, check=False)
                outside = [p for p in conflicted if not p.startswith(merge_ready.BASELINE_DIR)]
                raise Refused(
                    f"conflicts outside {merge_ready.BASELINE_DIR}: {', '.join(outside) or 'none listed'}"
                )
            for path in conflicted:
                git("checkout", "--theirs", "--", path, root=root)
                git("add", "--", path, root=root)
            git("commit", "-q", "--no-edit", root=root)
        if git("rev-parse", "HEAD", root=root).stdout.strip() == before:
            raise Refused(f"{branch} already contains {merge_ready.BASE_BRANCH}")
        if record(root) != 0:
            raise Refused("make eval-baseline refused (a regression, or the eval did not run)")
        git("add", "--", merge_ready.BASELINE_DIR, root=root)
        if git("diff", "--cached", "--quiet", root=root, check=False).returncode:
            git(
                "commit",
                "-q",
                "-m",
                f"Re-record eval/baseline after merging {merge_ready.BASE_BRANCH} (decision 0093)\n\n{COMMIT_TRAILER}",
                root=root,
            )
        head = git("rev-parse", "HEAD", root=root).stdout.strip()
        git("push", "-q", REMOTE, f"HEAD:refs/heads/{branch}", root=root)
        return head
    finally:
        git("merge", "--abort", root=root, check=False)
        git("checkout", "-q", "-f", "--detach", start, root=root, check=False)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--pr", required=True, help="the ejected PR's number")
    args = parser.parse_args(argv)
    client = gh_client.from_remote(ROOT)
    if client is None:
        print("merge_catchup: origin is not a github.com remote", file=sys.stderr)
        return 2
    try:
        pr = gh_client.number(args.pr)
        pull = client.pull(pr)
        if merge_ready.field_of(pull, "merged") is True or merge_ready.text_of(pull, "state") != "open":
            raise Refused(f"#{pr} is not open")
        if merge_ready.text_of(pull, "head", "repo", "full_name") != merge_ready.text_of(
            pull, "base", "repo", "full_name"
        ):
            raise Refused(f"#{pr} comes from a fork")
        head = catch_up(ROOT, merge_ready.text_of(pull, "head", "ref"))
    except Refused as refusal:
        print(f"merge_catchup: not catching up #{args.pr}: {refusal}", file=sys.stderr)
        return 1
    except (gh_client.GhError, GitError) as error:
        print(f"merge_catchup: {error}", file=sys.stderr)
        return 2
    print(f"#{pr}: pushed {head}; when CI is green, run make mark-ready PR={pr} CARRY=1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
