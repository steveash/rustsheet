#!/usr/bin/env python3
"""Known-failure cells that only open desktop-evidence (M14) tasks own (decision 0143).

  scripts/desktop_owned.py [--out PATH] [--baseline DIR] [--tasks DIR]

Reads every `eval/baseline/*.txt` (its `C` lines name every case, its `F` lines the known
failures) and lists each failing cell (an `F` item `Sheet!A1`; a whole-case item such as `*` or
`!EngineError` is no cell) that an open task of milestone M14 owns and no open task of any other
milestone owns, one per line as `case!Sheet!A1<TAB>T-<owner>` (the first owning M14 task in path
order). Ownership is scripts/exit_owners.py's `owned` rule over the baseline's case ids, so one
definition decides it (directive 3). Writes to `--out`, or stdout.

`make eval` writes the list to eval/runs/desktop-owned.tsv and passes it to `rustsheet-eval run
--desktop-owned`: the Phase 1 rate (`v15_checkpoint`) leaves out the listed cells that are visibly
off in the run and reports them per function as `desktop_owned`. The list is regenerated by every
`make eval` from committed files, so it is never committed and never stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import exit_owners  # noqa: E402 (the sys.path line above must run first)
import tasks  # noqa: E402
from exit_owners import ExitCell  # noqa: E402

BASELINE = exit_owners.ROOT / "eval" / "baseline"
# Decision 0039 rule 3: work that needs desktop Excel evidence is M14 and blocks no phase exit.
DESKTOP = "M14"
GROUP = "desktop"
# A cell item of an `F` line, as `CellResult::key` writes it.
CELL_ITEM = re.compile(r".+![A-Z]{1,3}[0-9]{1,7}")


def baseline_items(baseline_dir: Path) -> tuple[list[str], list[ExitCell]]:
    """Every case id of the baselines, and every failing cell, in file and line order."""
    cases: list[str] = []
    cells: list[ExitCell] = []
    for path in sorted(baseline_dir.glob("*.txt")):
        for line in path.read_text().splitlines():
            fields = line.split("\t")
            if len(fields) != 3:
                continue
            kind, case, item = fields
            if kind == "C":
                cases.append(case)
            elif kind == "F" and CELL_ITEM.fullmatch(item):
                cells.append(ExitCell(GROUP, case, item, ""))
    return cases, cells


def desktop_owned(baseline_dir: Path, tasks_dir: Path) -> list[tuple[ExitCell, str]]:
    """The failing cells only open M14 tasks own, each with its first M14 owner."""
    cases, cells = baseline_items(baseline_dir)
    called = exit_owners.case_names(cases + [c.case for c in cells])
    open_tasks = exit_owners.open_tasks(tasks_dir)
    desktop = [
        (str(m["id"]), t) for m, t in open_tasks if m.get("milestone") == DESKTOP
    ]
    others = [t for m, t in open_tasks if m.get("milestone") != DESKTOP]
    # Texts narrowed to the ones naming the case, once per case (as exit_owners.unowned_off does);
    # the other milestones' texts only for a case some M14 task names.
    mine: dict[str, list[tuple[str, str]]] = {}
    theirs: dict[str, list[str]] = {}
    out = []
    for c in cells:
        names = called[c.case]
        if c.case not in mine:
            mine[c.case] = [(i, t) for i, t in desktop if exit_owners.names_case(t, names)]
        owner = next((i for i, t in mine[c.case] if exit_owners.owned(c, [t], names)), None)
        if owner is None:
            continue
        if c.case not in theirs:
            theirs[c.case] = [t for t in others if exit_owners.names_case(t, names)]
        if not exit_owners.owned(c, theirs[c.case], names):
            out.append((c, owner))
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, help="write here instead of stdout")
    ap.add_argument("--baseline", type=Path, default=BASELINE)
    ap.add_argument("--tasks", type=Path, default=tasks.TASKS)
    args = ap.parse_args(argv)
    lines = [f"{c.case}!{c.key}\t{owner}\n" for c, owner in desktop_owned(args.baseline, args.tasks)]
    text = "".join(lines)
    if args.out is None:
        sys.stdout.write(text)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
        print(f"{len(lines)} known-failure cells are owned only by open {DESKTOP} tasks: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
